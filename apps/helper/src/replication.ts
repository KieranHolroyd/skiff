import { ValidationError, assertDatabaseId } from './validate.ts';

/**
 * Postgres streaming replication: the helper's fixed pieces (docs/CLUSTERING.md §9.2, C7).
 *
 * Everything here is pure so it can be tested without Postgres or Podman. Nothing from the wire
 * reaches SQL or a file except slot names (a fixed `yoal_[a-z0-9_]` pattern) and the replication
 * password (base64url), both validated before they are rendered.
 */

/** The `LOGIN REPLICATION` role on a primary. Same value as `@yoal/contracts`. */
export const REPLICATION_USER = 'yoal_repl';
/** Physical slots Yoal owns; the helper never creates, drops or reports any other slot. */
export const REPLICATION_SLOT_PATTERN = /^yoal_[a-z0-9_]{1,56}$/;
export const REPLICATION_MAX_SLOTS = 8;
/** Replica workload ids (`db_dbr_<hex>`). */
export const REPLICA_ID_PREFIX = 'db_dbr_';
/** Where a replica container finds the agent's link socket (`.s.PGSQL.5432`). */
export const REPLICA_UPSTREAM_DIR = '/run/yoal-upstream';
/** The helper-written standby start script, mounted read-only into the replica container. */
export const REPLICA_START_SCRIPT = '/usr/local/bin/yoal-replica-start';
/** WAL a primary keeps for its replicas (§9.2 defaults). */
export const REPLICATION_WAL_KEEP_SIZE = '512MB';
export const REPLICATION_MAX_SLOT_WAL_KEEP_SIZE = '2GB';

export const HBA_BEGIN = '# BEGIN yoal replication (managed by yoal-helper; do not edit)';
export const HBA_END = '# END yoal replication';
/**
 * The replica reaches the primary's published loopback port through the agent's link, so the
 * address Postgres sees is the container network's gateway, not a fixed one. The port is never
 * published beyond loopback (D56) and the overlay hop is pinned mTLS, so the rule admits only the
 * replication role, only for replication, only with its password.
 */
export const HBA_RULE = `host replication ${REPLICATION_USER} all scram-sha-256`;

export function assertReplicaWorkloadId(value: unknown, label = 'replica id'): string {
	const id = assertDatabaseId(value, label);
	if (!id.startsWith(REPLICA_ID_PREFIX) || id.length === REPLICA_ID_PREFIX.length)
		throw new ValidationError(`${label} must start with "${REPLICA_ID_PREFIX}"`);
	return id;
}

/** A database id that is not a replica (the id a promoted replica's data dir is handed to). */
export function assertPrimaryDatabaseId(value: unknown, label = 'database id'): string {
	const id = assertDatabaseId(value, label);
	if (id.startsWith(REPLICA_ID_PREFIX)) throw new ValidationError(`${label} must not be a replica id`);
	return id;
}

export function assertSlot(value: unknown, label = 'slot'): string {
	if (typeof value !== 'string' || !REPLICATION_SLOT_PATTERN.test(value))
		throw new ValidationError(`${label} must match ${REPLICATION_SLOT_PATTERN.source}`);
	return value;
}

export function parseSlots(value: unknown, label = 'slots'): string[] {
	if (!Array.isArray(value)) throw new ValidationError(`${label} must be an array`);
	if (value.length > REPLICATION_MAX_SLOTS) throw new ValidationError(`${label} allows at most ${REPLICATION_MAX_SLOTS} entries`);
	const slots = value.map((item, index) => assertSlot(item, `${label}[${index}]`));
	if (new Set(slots).size !== slots.length) throw new ValidationError(`${label} must not repeat a slot`);
	return [...slots].sort();
}

/** Null tears replication down; otherwise base64url, like every other generated password. */
export function parseReplicationPassword(value: unknown, slots: readonly string[]): string | null {
	if (slots.length === 0) {
		if (value !== null && value !== undefined) throw new ValidationError('password must be null when slots is empty');
		return null;
	}
	if (typeof value !== 'string' || !/^[A-Za-z0-9_-]{16,200}$/.test(value))
		throw new ValidationError('password must be base64url (16–200 characters)');
	return value;
}

/**
 * The standby start script. On first start (no `PG_VERSION`) it copies the primary through the
 * link socket with `pg_basebackup`, retrying until the primary answers; the copy lands in
 * `pgdata.partial` and is moved into place only when complete. Every start then marks the cluster
 * as a standby, so a replica unit can never come up as a second primary, and execs the image's
 * own entrypoint with the arguments the unit passes after the slot name.
 */
export function renderReplicaStartScript(): string {
	return `#!/bin/sh
# Generated by yoal-helper. Do not edit; changes are overwritten.
# Yoal read replica: copy the primary once, then run as a hot standby (docs/CLUSTERING.md 9.2).
set -eu
slot="$1"
shift
data=/data/pgdata
partial=/data/pgdata.partial
if [ ! -s "$data/PG_VERSION" ]; then
	rm -rf "$data" "$partial"
	until pg_basebackup --host=${REPLICA_UPSTREAM_DIR} --port=5432 --username=${REPLICATION_USER} --no-password \\
		--pgdata="$partial" --wal-method=stream --checkpoint=fast --max-rate=50M --slot="$slot"; do
		echo "yoal-replica: base backup from the primary failed; retrying in 10 s" >&2
		rm -rf "$partial"
		sleep 10
	done
	mv "$partial" "$data"
fi
touch "$data/standby.signal"
exec /usr/local/bin/docker-entrypoint.sh "$@"
`;
}

/** The standby settings the replica unit passes to `postgres` (after the primary's own flags). */
export function replicaPostgresArgs(slot: string): string[] {
	assertSlot(slot);
	return [
		'-c',
		'hot_standby=on',
		// Long read queries are not cancelled by vacuum on the primary; the price is some bloat.
		'-c',
		'hot_standby_feedback=on',
		'-c',
		`primary_conninfo=host=${REPLICA_UPSTREAM_DIR} port=5432 user=${REPLICATION_USER} application_name=${slot} connect_timeout=10`,
		'-c',
		`primary_slot_name=${slot}`,
		'-c',
		'wal_receiver_timeout=60s',
	];
}

/**
 * `pg_hba.conf` with the managed replication block present (after everything else, so an
 * operator's own rule still wins) or removed. Idempotent; any older copy of the block is replaced.
 */
export function withReplicationHba(current: string, enabled: boolean): string {
	const lines = current.split('\n');
	const kept: string[] = [];
	let inside = false;
	for (const line of lines) {
		if (line.trim() === HBA_BEGIN) {
			inside = true;
			continue;
		}
		if (inside) {
			if (line.trim() === HBA_END) inside = false;
			continue;
		}
		kept.push(line);
	}
	while (kept.length > 0 && kept[kept.length - 1] === '') kept.pop();
	if (enabled) kept.push('', HBA_BEGIN, HBA_RULE, HBA_END);
	return `${kept.join('\n')}\n`;
}

function slotArray(slots: readonly string[]): string {
	for (const slot of slots) assertSlot(slot);
	return slots.length === 0 ? 'ARRAY[]::text[]' : `ARRAY[${slots.map((slot) => `'${slot}'`).join(', ')}]::text[]`;
}

/** Drop every Yoal slot not in `keep`, ending its walsender first. Retried by the agent on error. */
function dropOtherSlotsSql(keep: readonly string[]): string {
	return `DO $$
DECLARE s record;
BEGIN
  FOR s IN SELECT slot_name, active_pid FROM pg_replication_slots
    WHERE slot_type = 'physical' AND slot_name LIKE 'yoal\\_%' AND NOT (slot_name = ANY(${slotArray(keep)})) LOOP
    IF s.active_pid IS NOT NULL THEN
      PERFORM pg_terminate_backend(s.active_pid);
      PERFORM pg_sleep(1);
    END IF;
    PERFORM pg_drop_replication_slot(s.slot_name);
  END LOOP;
END $$;`;
}

/**
 * Configure a primary for these replicas: the role and its password, WAL retention, exactly these
 * slots (created reserving WAL immediately), and a reload. Sent over stdin, never argv.
 */
export function renderReplicationConfigureSql(password: string, slots: readonly string[]): string {
	if (!/^[A-Za-z0-9_-]{16,200}$/.test(password)) throw new ValidationError('password must be base64url (16–200 characters)');
	if (slots.length === 0) throw new ValidationError('use the teardown SQL when no slot is wanted');
	return [
		`DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${REPLICATION_USER}') THEN
    CREATE ROLE ${REPLICATION_USER} WITH LOGIN REPLICATION PASSWORD '${password}';
  ELSE
    ALTER ROLE ${REPLICATION_USER} WITH LOGIN REPLICATION PASSWORD '${password}';
  END IF;
END $$;`,
		`ALTER SYSTEM SET wal_keep_size = '${REPLICATION_WAL_KEEP_SIZE}';`,
		`ALTER SYSTEM SET max_slot_wal_keep_size = '${REPLICATION_MAX_SLOT_WAL_KEEP_SIZE}';`,
		`ALTER SYSTEM SET wal_sender_timeout = '60s';`,
		'SELECT pg_reload_conf();',
		`SELECT pg_create_physical_replication_slot(s, true) FROM unnest(${slotArray(slots)}) AS s
  WHERE s NOT IN (SELECT slot_name FROM pg_replication_slots);`,
		dropOtherSlotsSql(slots),
		'',
	].join('\n');
}

/** Tear replication down: every Yoal slot, the role and the WAL settings. */
export function renderReplicationTeardownSql(): string {
	return [
		dropOtherSlotsSql([]),
		`DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${REPLICATION_USER}') THEN
    DROP ROLE ${REPLICATION_USER};
  END IF;
END $$;`,
		'ALTER SYSTEM RESET wal_keep_size;',
		'ALTER SYSTEM RESET max_slot_wal_keep_size;',
		'ALTER SYSTEM RESET wal_sender_timeout;',
		'SELECT pg_reload_conf();',
		'',
	].join('\n');
}

/**
 * One query, one JSON line: each Yoal slot joined to its walsender. Lag in bytes is measured from
 * the replica's replay position while connected, else from what the slot still retains.
 */
export const REPLICATION_STATUS_SQL = `SELECT coalesce(json_agg(json_build_object(
  'slot', s.slot_name,
  'active', s.active,
  'walStatus', s.wal_status,
  'state', r.state,
  'sentLsn', r.sent_lsn::text,
  'replayLsn', r.replay_lsn::text,
  'lagBytes', CASE WHEN coalesce(r.replay_lsn, s.restart_lsn) IS NULL THEN NULL
    ELSE greatest(0, pg_wal_lsn_diff(pg_current_wal_lsn(), coalesce(r.replay_lsn, s.restart_lsn)))::bigint END,
  'lagSeconds', CASE WHEN r.state = 'streaming' THEN coalesce(extract(epoch FROM r.replay_lag), 0)::float8 ELSE NULL END,
  'syncState', r.sync_state
) ORDER BY s.slot_name), '[]'::json)
FROM pg_replication_slots s LEFT JOIN pg_stat_replication r ON r.pid = s.active_pid
WHERE s.slot_type = 'physical' AND s.slot_name LIKE 'yoal\\_%'`;

export interface ReplicationSlotStatus {
	slot: string;
	active: boolean;
	walStatus: string | null;
	state: string | null;
	sentLsn: string | null;
	replayLsn: string | null;
	lagBytes: number | null;
	lagSeconds: number | null;
	syncState: string | null;
}

const LSN = /^[0-9A-F]{1,8}\/[0-9A-F]{1,8}$/i;

/** Parse `REPLICATION_STATUS_SQL`'s output strictly; anything unexpected is dropped, not trusted. */
export function parseReplicationStatus(stdout: string): ReplicationSlotStatus[] {
	const text = stdout.trim();
	if (!text) return [];
	let parsed: unknown;
	try {
		parsed = JSON.parse(text);
	} catch {
		throw new ValidationError('The replication status query did not return JSON.');
	}
	if (!Array.isArray(parsed)) throw new ValidationError('The replication status query did not return a list.');
	const out: ReplicationSlotStatus[] = [];
	for (const item of parsed.slice(0, 32)) {
		if (!item || typeof item !== 'object') continue;
		const row = item as Record<string, unknown>;
		if (typeof row.slot !== 'string' || !REPLICATION_SLOT_PATTERN.test(row.slot)) continue;
		const text = (value: unknown, max = 32) => (typeof value === 'string' && value.length <= max ? value : null);
		const lsn = (value: unknown) => (typeof value === 'string' && LSN.test(value) ? value : null);
		const count = (value: unknown) =>
			typeof value === 'number' && Number.isFinite(value) && value >= 0 ? Math.round(value) : null;
		const seconds = (value: unknown) => (typeof value === 'number' && Number.isFinite(value) && value >= 0 ? value : null);
		out.push({
			slot: row.slot,
			active: row.active === true,
			walStatus: text(row.walStatus),
			state: text(row.state),
			sentLsn: lsn(row.sentLsn),
			replayLsn: lsn(row.replayLsn),
			lagBytes: count(row.lagBytes),
			lagSeconds: seconds(row.lagSeconds),
			syncState: text(row.syncState),
		});
	}
	return out;
}

/** `pg_ctl promote` inside the replica container, waiting up to 60 s for it to finish. */
export function renderPromoteArgs(podmanPath: string, workloadId: string): string[] {
	assertReplicaWorkloadId(workloadId, 'replica id');
	return [podmanPath, 'exec', `yoal-workload-${workloadId}`, 'pg_ctl', 'promote', '-D', '/data/pgdata', '-w', '-t', '60'];
}
