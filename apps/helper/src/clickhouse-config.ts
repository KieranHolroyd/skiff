import { createHash } from 'node:crypto';
import { DUMP_STAGING_CONTAINER_DIR } from './database-dumps.ts';
import { ValidationError } from './validate.ts';

/**
 * Managed ClickHouse databases (docs/DATABASES.md §17). The helper writes a complete standalone
 * server config and its users file into one 0700 directory, owned by the image's uid and mounted
 * read-only at `CLICKHOUSE_CONFIG_DIR`; the image entrypoint reads `CLICKHOUSE_CONFIG` from the
 * fixed env and still creates the owner's database on first start.
 *
 * Like the platform's own telemetry store (scripts/systemd/clickhouse.ts, D101) the server logs to
 * stderr only, keeps its data under the `/data` mount, has small fixed caches and no system log
 * tables except a 7-day `query_log`. Unlike it, the server listens on the container network (HTTP
 * 8123 and native 9000; only HTTP is published, on loopback) and the owner manages access.
 *
 * The users file is a directory entry, not a single-file mount, so a rewrite (rename into place)
 * is visible inside the container: ClickHouse reloads users on its own, which is how owner rotation
 * takes effect without a restart.
 */

/** Where the container sees the helper-written config directory. */
export const CLICKHOUSE_CONFIG_DIR = '/etc/skiff/clickhouse';
/** Host-side directory name beside the env file. */
export const CLICKHOUSE_CONFIG_DIRNAME = 'clickhouse';
export const CLICKHOUSE_CONFIG_FILE = 'config.xml';
export const CLICKHOUSE_USERS_FILE = 'users.xml';
/** The server's `<path>`, inside the `/data` mount. */
export const CLICKHOUSE_DATA_PATH = '/data/clickhouse/';

/**
 * System log tables that are off. On a small instance they dominate disk and RAM and nothing reads
 * them; `query_log` stays, with a short TTL, because it is how users find slow queries.
 */
const DISABLED_SYSTEM_LOGS = [
	'query_thread_log',
	'query_views_log',
	'query_metric_log',
	'part_log',
	'trace_log',
	'metric_log',
	'transposed_metric_log',
	'asynchronous_metric_log',
	'text_log',
	'session_log',
	'opentelemetry_span_log',
	'processors_profile_log',
	'asynchronous_insert_log',
	'backup_log',
	'blob_storage_log',
	'background_schedule_pool_log',
	'latency_log',
	'error_log',
	's3queue_log',
	'azure_queue_log',
	'crash_log',
	'zookeeper_log',
	'filesystem_cache_log',
	'filesystem_read_prefetches_log',
	'iceberg_metadata_log',
	'delta_lake_metadata_log',
	'dead_letter_queue',
	'object_storage_queue_log',
];

const MB = 1024 * 1024;

/** Memory figures derived from the unit's `MemoryMax`, in bytes. */
export function clickhouseMemory(memoryMb: number): {
	server: number;
	merges: number;
	markCache: number;
} {
	const total = Math.max(1, Math.floor(memoryMb)) * MB;
	return {
		// The server refuses queries before the cgroup OOM-kills it.
		server: Math.floor(total * 0.75),
		merges: Math.floor(total * 0.25),
		markCache: Math.max(32 * MB, Math.min(512 * MB, Math.floor(total * 0.05))),
	};
}

/**
 * The standalone server config. Every path lives under `/data`, logs go to stderr (journald), and
 * nothing writes outside the data mount and `/tmp`, so the root filesystem stays read-only.
 */
export function renderClickHouseServerConfig(options: { memoryMb: number }): string {
	if (!Number.isInteger(options.memoryMb) || options.memoryMb < 256)
		throw new ValidationError('ClickHouse needs an integer memory limit of at least 256 MB');
	const memory = clickhouseMemory(options.memoryMb);
	const data = CLICKHOUSE_DATA_PATH;
	const logs = DISABLED_SYSTEM_LOGS.map((name) => `\t<${name} remove="1"/>`).join('\n');
	return `<?xml version="1.0"?>
<!-- Generated by skiff-helper. Do not edit; changes are overwritten. -->
<clickhouse>
	<logger>
		<level>warning</level>
		<console>1</console>
		<console_log_level>warning</console_log_level>
	</logger>

	<!-- The container network only: the host publishes HTTP on loopback (D56). -->
	<listen_host>::</listen_host>
	<listen_host>0.0.0.0</listen_host>
	<listen_try>1</listen_try>
	<http_port>8123</http_port>
	<tcp_port>9000</tcp_port>
	<max_connections>256</max_connections>
	<keep_alive_timeout>30</keep_alive_timeout>

	<path>${data}</path>
	<tmp_path>${data}tmp/</tmp_path>
	<user_files_path>${data}user_files/</user_files_path>
	<format_schema_path>${data}format_schemas/</format_schema_path>
	<user_scripts_path>${data}user_scripts/</user_scripts_path>
	<user_defined_path>${data}user_defined/</user_defined_path>
	<custom_cached_disks_base_directory>${data}caches/</custom_cached_disks_base_directory>

	<!-- The helper's BACKUP/RESTORE verbs stage archives here, inside the data mount (§8). -->
	<backups>
		<allowed_path>${DUMP_STAGING_CONTAINER_DIR}</allowed_path>
	</backups>

	<!-- The owner from users.xml; SQL-created users and roles persist under the data dir. -->
	<user_directories>
		<users_xml>
			<path>${CLICKHOUSE_USERS_FILE}</path>
		</users_xml>
		<local_directory>
			<path>${data}access/</path>
		</local_directory>
	</user_directories>
	<default_profile>default</default_profile>
	<default_database>default</default_database>
	<timezone>UTC</timezone>
	<display_name>skiff</display_name>

	<max_server_memory_usage>${memory.server}</max_server_memory_usage>
	<merges_mutations_memory_usage_soft_limit>${memory.merges}</merges_mutations_memory_usage_soft_limit>
	<mark_cache_size>${memory.markCache}</mark_cache_size>
	<uncompressed_cache_size>0</uncompressed_cache_size>
	<index_mark_cache_size>${16 * MB}</index_mark_cache_size>
	<index_uncompressed_cache_size>0</index_uncompressed_cache_size>
	<primary_index_cache_size>${32 * MB}</primary_index_cache_size>
	<query_condition_cache_size>${16 * MB}</query_condition_cache_size>
	<mmap_cache_size>256</mmap_cache_size>
	<compiled_expression_cache_size>${16 * MB}</compiled_expression_cache_size>
	<compiled_expression_cache_elements_size>1000</compiled_expression_cache_elements_size>
	<mlock_executable>false</mlock_executable>
	<remap_executable>false</remap_executable>

	<max_concurrent_queries>50</max_concurrent_queries>
	<max_thread_pool_free_size>32</max_thread_pool_free_size>
	<background_pool_size>4</background_pool_size>
	<background_merges_mutations_concurrency_ratio>2</background_merges_mutations_concurrency_ratio>
	<background_schedule_pool_size>8</background_schedule_pool_size>
	<background_common_pool_size>4</background_common_pool_size>
	<background_move_pool_size>2</background_move_pool_size>
	<background_fetches_pool_size>2</background_fetches_pool_size>
	<background_buffer_flush_schedule_pool_size>2</background_buffer_flush_schedule_pool_size>
	<background_message_broker_schedule_pool_size>2</background_message_broker_schedule_pool_size>
	<background_distributed_schedule_pool_size>2</background_distributed_schedule_pool_size>
	<asynchronous_metrics_update_period_s>30</asynchronous_metrics_update_period_s>

	<merge_tree>
		<!-- Must fit background_pool_size x concurrency_ratio (8 slots) or tables refuse to load. -->
		<number_of_free_entries_in_pool_to_lower_max_size_of_merge>4</number_of_free_entries_in_pool_to_lower_max_size_of_merge>
		<number_of_free_entries_in_pool_to_execute_mutation>4</number_of_free_entries_in_pool_to_execute_mutation>
		<number_of_free_entries_in_pool_to_execute_optimize_entire_partition>4</number_of_free_entries_in_pool_to_execute_optimize_entire_partition>
	</merge_tree>

	<send_crash_reports>
		<enabled>false</enabled>
	</send_crash_reports>

	<query_log>
		<database>system</database>
		<table>query_log</table>
		<partition_by>toYYYYMM(event_date)</partition_by>
		<ttl>event_date + INTERVAL 7 DAY DELETE</ttl>
		<flush_interval_milliseconds>7500</flush_interval_milliseconds>
	</query_log>

${logs}
</clickhouse>
`;
}

const LOCKED_PASSWORD_HASH = '0'.repeat(64);

/**
 * The users file: the database's owner is the only usable configured user, may manage
 * SQL users, roles and quotas (`access_management`), and authenticates with a SHA-256 of the
 * password, so the plaintext stays in the 0400 env file. It depends only on the owner, so a
 * rotation re-renders it without knowing the unit's limits; memory is bounded server-wide.
 */
export function renderClickHouseUsers(options: { user: string; password: string }): string {
	if (!/^[a-z][a-z0-9_]{0,62}$/.test(options.user)) throw new ValidationError('Invalid ClickHouse user name');
	if (!/^[A-Za-z0-9_-]{16,200}$/.test(options.password))
		throw new ValidationError('The ClickHouse password must be base64url (16–200 characters)');
	const hash = createHash('sha256').update(options.password).digest('hex');
	return `<?xml version="1.0"?>
<!-- Generated by skiff-helper. Do not edit; changes are overwritten. -->
<clickhouse>
	<profiles>
		<default>
			<log_queries>1</log_queries>
		</default>
	</profiles>

	<quotas>
		<default>
			<interval>
				<duration>3600</duration>
				<queries>0</queries>
				<errors>0</errors>
				<result_rows>0</result_rows>
				<read_rows>0</read_rows>
				<execution_time>0</execution_time>
			</interval>
		</default>
	</quotas>

	<users>
		<!--
			Locked: the image entrypoint reads users.default and exits when it is missing. The hash
			(all zeros) has no known preimage, so nobody can log in as it, and only from loopback.
		-->
		<default>
			<password_sha256_hex>${LOCKED_PASSWORD_HASH}</password_sha256_hex>
			<networks>
				<ip>::1</ip>
			</networks>
			<profile>default</profile>
			<quota>default</quota>
			<access_management>0</access_management>
		</default>
		<${options.user}>
			<password_sha256_hex>${hash}</password_sha256_hex>
			<networks>
				<ip>::/0</ip>
			</networks>
			<profile>default</profile>
			<quota>default</quota>
			<access_management>1</access_management>
			<named_collection_control>1</named_collection_control>
			<show_named_collections>1</show_named_collections>
			<show_named_collections_secrets>1</show_named_collections_secrets>
		</${options.user}>
	</users>
</clickhouse>
`;
}
