/**
 * The preload that lets an unchanged Node.js app run socket-activated (D125).
 *
 * systemd hands a socket-activated unit its listener as fd 3 and sets `LISTEN_FDS`; it sets no
 * `PORT`. Most Node servers (Express, Fastify, Next.js, Nuxt, Remix, Hono's node adapter) call
 * `server.listen(port)` and know nothing about inherited sockets. This file is loaded with
 * `NODE_OPTIONS=--require=…` and rewrites the first TCP `listen()` of the process to
 * `listen({ fd: 3 })`, so the app serves on the socket the unit was given, Caddy's upstream stays
 * the project socket, and the app can scale to zero (D121) like a function.
 *
 * Rules, in the order they matter:
 * - Only when `LISTEN_FDS` is set. Without socket activation the helper sets `PORT`/`HOST` and
 *   never loads this file; locally it is a no-op.
 * - `LISTEN_PID` is deliberately not checked. `node --run start` (the Node default command) runs
 *   the script in a child process, so the server is never systemd's main pid, but it inherits
 *   fd 3 and the environment.
 * - Only the first TCP listen is adopted, then `LISTEN_*` is removed from `process.env`, so a
 *   second server, or a child spawned after that, binds normally instead of fighting over fd 3.
 * - A listen on a unix path, an fd or a handle is the app's own choice and passes through. An app
 *   that adopts fd 3 itself (SvelteKit's adapter-node does) therefore keeps working.
 *
 * The source is plain CommonJS with no imports beyond `node:net`, because it runs before the
 * app's own module system is set up and must work for both CommonJS and ESM apps.
 */
export const NODE_LISTEN_CREDENTIAL = 'skiff-node-listen.cjs';

export const NODE_LISTEN_SOURCE = `'use strict';
// Generated by skiff-helper (D125): adopt the systemd listen socket for the first TCP listen().
(function () {
	if (!(Number(process.env.LISTEN_FDS) >= 1)) return;
	const net = require('node:net');
	const listen = net.Server.prototype.listen;
	let adopted = false;
	function isTcp(args) {
		const first = args[0];
		if (first === undefined || first === null || typeof first === 'function') return true;
		if (typeof first === 'number') return true;
		if (typeof first === 'string') return /^\\d+$/.test(first);
		if (typeof first === 'object') {
			if ('fd' in first || '_handle' in first || 'handle' in first) return false;
			if (typeof first.path === 'string') return false;
			return true;
		}
		return false;
	}
	net.Server.prototype.listen = function skiffListen(...args) {
		if (adopted || !isTcp(args)) return listen.apply(this, args);
		adopted = true;
		delete process.env.LISTEN_FDS;
		delete process.env.LISTEN_PID;
		delete process.env.LISTEN_FDNAMES;
		const callback = typeof args[args.length - 1] === 'function' ? args[args.length - 1] : undefined;
		return callback ? listen.call(this, { fd: 3 }, callback) : listen.call(this, { fd: 3 });
	};
})();
`;
