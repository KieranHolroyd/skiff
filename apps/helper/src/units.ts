/**
 * The fixed database profile (D55, D61). Image, user, mounts and the container port come from the
 * helper's registry; only the host port, limits and env file come from the (validated) request.
 * The port is published on loopback only: nothing listens on a public or WireGuard address (D56).
 */
export function renderDatabaseUnit(options: DatabaseUnitOptions): string {
	const { workload } = options;
	const database = workload.database;
	if (!database) throw new ValidationError('renderDatabaseUnit needs a database workload');
	const info = DATABASE_ENGINES[database.engine];
	const lines: string[] = [];
	lines.push('[Unit]');
	lines.push(`Description=Skiff database ${workload.id} (${workload.projectSlug}, ${database.engine} ${database.version})`);
	lines.push('After=network-online.target');
	lines.push('Wants=network-online.target');
	lines.push('StartLimitIntervalSec=300');
	lines.push('StartLimitBurst=10');
	lines.push('');
	lines.push('[Container]');
	lines.push(`ContainerName=skiff-workload-${workload.id}`);
	lines.push(`Image=${databaseImage(database)}`);
	// Keep the image entrypoint (initdb, then exec "$@") and pass the fixed Postgres flags. The
	// shared preload is required before `CREATE EXTENSION pg_stat_statements` can work. When PITR
	// is enabled the same Exec turns on WAL archiving; the pinned Postgres image must ship the
	// `pgbackrest` binary (docs/PITR.md).
	lines.push('Entrypoint=/usr/local/bin/docker-entrypoint.sh');
	const execArgs = [
		'postgres',
		'-c',
		'shared_preload_libraries=pg_stat_statements',
		'-c',
		'pg_stat_statements.track=all',
	];
	if (options.pitr) {
		execArgs.push(
			'-c',
			'wal_level=replica',
			'-c',
			'archive_mode=on',
			'-c',
			`archive_command=/usr/local/bin/pgbackrest --config=/etc/pgbackrest/pgbackrest.conf --stanza=${options.pitr.stanza} archive-push %p`,
			'-c',
			`archive_timeout=${options.pitr.archiveTimeoutSeconds}`,
		);
	}
	if (options.tlsDir) {
		execArgs.push(
			'-c',
			'ssl=on',
			'-c',
			'ssl_cert_file=/run/skiff-tls/server.crt',
			'-c',
			'ssl_key_file=/run/skiff-tls/server.key',
			'-c',
			'ssl_min_protocol_version=TLSv1.2',
		);
	}
	lines.push(`Exec=${execArgs.map(quoteSystemdArg).join(' ')}`);
	lines.push(`User=${info.uid}:${info.gid}`);
	lines.push(`PublishPort=127.0.0.1:${workload.port}:${info.containerPort}`);
	lines.push(`Network=${networkUnitName(workloadNetworkName(workload))}`);
	lines.push(`NetworkAlias=${databaseAlias(workload.id)}`);
	lines.push(`EnvironmentFile=${options.envFile}`);
	lines.push(`Volume=${options.dataDir}:/data:Z`);
	if (options.pitr) {
		lines.push(`Volume=${options.pitr.configPath}:/etc/pgbackrest/pgbackrest.conf:ro,Z`);
		lines.push(`Volume=${options.pitr.pgpassPath}:/etc/pgbackrest/pgpass:ro,Z`);
	}
	if (options.tlsDir) lines.push(`Volume=${options.tlsDir}:/run/skiff-tls:ro,Z`);
	// The socket dir is created 3777 by the image; ReadOnly=true needs it (and /tmp) on tmpfs.
	lines.push('Tmpfs=/var/run/postgresql:rw,size=8m,mode=1777');
	lines.push('Tmpfs=/tmp:rw,size=64m');
	lines.push('DropCapability=all');
	lines.push('NoNewPrivileges=true');
	lines.push('ReadOnly=true');
	lines.push('');
	lines.push('[Service]');
	lines.push('Restart=on-failure');
	lines.push('RestartSec=5');
	// The first start pulls the image and runs initdb; a clean shutdown flushes WAL.
	lines.push('TimeoutStartSec=600');
	lines.push('TimeoutStopSec=120');
	lines.push(`MemoryMax=${workload.memoryMb}M`);
	lines.push(`CPUQuota=${cpuQuota(workload.cpus)}`);
	lines.push(`Slice=${WORKLOAD_SLICE}`);
	lines.push('');
	lines.push('[Install]');
	lines.push('WantedBy=default.target');
	return `${lines.join('\n')}\n`;
}

/**
 * The fixed object-storage profile (S1, S2). Like the database profile, the image (pinned by
 * digest), user, mounts and container port come from the helper's registry; only the host port,
 * limits and env file come from the (validated) request. The S3 port is published on loopback
 * only; public access goes through Caddy (S3).
 */
export function renderStorageUnit(options: DatabaseUnitOptions): string {
	const { workload } = options;
	const storage = workload.objectStorage;
	if (!storage) throw new ValidationError('renderStorageUnit needs an objectStorage workload');
	const info = STORAGE_ENGINES[storage.engine];
	const lines: string[] = [];
	lines.push('[Unit]');
	lines.push(`Description=Skiff storage ${workload.id} (${workload.projectSlug}, ${storage.engine} ${storage.version})`);
	lines.push('After=network-online.target');
	lines.push('Wants=network-online.target');
	lines.push('StartLimitIntervalSec=300');
	lines.push('StartLimitBurst=10');
	lines.push('');
	lines.push('[Container]');
	lines.push(`ContainerName=skiff-workload-${workload.id}`);
	lines.push(`Image=${storageImage(storage)}`);
	lines.push(`User=${info.uid}:${info.gid}`);
	lines.push(`PublishPort=127.0.0.1:${workload.port}:${info.containerPort}`);
	lines.push(`Network=${networkUnitName(workloadNetworkName(workload))}`);
	lines.push(`NetworkAlias=${storageAlias(workload.id)}`);
	lines.push(`EnvironmentFile=${options.envFile}`);
	lines.push(`Volume=${options.dataDir}:/data:Z`);
	lines.push('Tmpfs=/tmp:rw,size=64m');
	lines.push('DropCapability=all');
	lines.push('NoNewPrivileges=true');
	lines.push('ReadOnly=true');
	lines.push('');
	lines.push('[Service]');
	lines.push('Restart=on-failure');
	lines.push('RestartSec=5');
	// The first start pulls the image.
	lines.push('TimeoutStartSec=600');
	lines.push('TimeoutStopSec=60');
	lines.push(`MemoryMax=${workload.memoryMb}M`);
	lines.push(`CPUQuota=${cpuQuota(workload.cpus)}`);
	lines.push(`Slice=${WORKLOAD_SLICE}`);
	lines.push('');
	lines.push('[Install]');
	lines.push('WantedBy=default.target');
	return `${lines.join('\n')}\n`;
}

function cpuQuota(cpus: number): string {
	const percent = Math.max(1, Math.round(cpus * 100));
	return `${percent}%`;
}
