/**
 * Quadlet `.container`. Quadlet turns this into `skiff-workload-<id>.service`; the `[Service]`
 * section carries the same slice/memory/CPU caps as a process unit.
 */
export function renderContainerUnit(options: ContainerUnitOptions): string {
	const { workload } = options;
	if (workload.database)
		return renderDatabaseUnit({
			workload,
			envFile: options.envFile,
			dataDir: options.dataDir,
			...(options.pitr ? { pitr: options.pitr } : {}),
			tlsDir: options.tlsDir ?? null,
			serverConfigPath: options.serverConfigPath ?? null,
			apparmorProfile: options.apparmorProfile ?? null,
			...(options.replica ? { replica: options.replica } : {}),
		});
	if (workload.objectStorage)
		return renderStorageUnit({
			workload,
			envFile: options.envFile,
			dataDir: options.dataDir,
			apparmorProfile: options.apparmorProfile ?? null,
		});
	if (workload.registry)
		return renderRegistryUnit({
			workload,
			envFile: options.envFile,
			dataDir: options.dataDir,
			configDir: options.serverConfigPath ?? null,
			apparmorProfile: options.apparmorProfile ?? null,
		});
	if (workload.broker)
		return renderBrokerUnit({
			workload,
			envFile: options.envFile,
			dataDir: options.dataDir,
			serverConfigPath: options.serverConfigPath ?? null,
			apparmorProfile: options.apparmorProfile ?? null,
		});
	const lines: string[] = [];
	lines.push('[Unit]');
	lines.push(`Description=${description(workload)} (container)`);
	lines.push('After=network-online.target');
	lines.push('Wants=network-online.target');
	lines.push('StartLimitIntervalSec=60');
	lines.push('StartLimitBurst=10');
	lines.push('');
	lines.push('[Container]');
	lines.push(`ContainerName=skiff-workload-${workload.id}`);
	lines.push(`Image=${options.image}`);
	const runner = Boolean(workload.runner);
	if (runner) {
		// Ephemeral runners (plan 21, D91): always the newest image, a fixed entrypoint, and a fresh
		// container per job (Quadlet runs `podman run --rm`), so no job sees another job's files.
		lines.push('Pull=newer');
		lines.push(`Exec=${RUNNER_ENTRYPOINT}`);
	}
	// Caddy on the host proxies to loopback; the container listens on the declared port. Workers
	// (plan 21) publish nothing: they only make outbound connections.
	if (workload.ingress !== 'none') lines.push(`PublishPort=127.0.0.1:${workload.port}:${workload.port}`);
	lines.push(`Network=${networkUnitName(workloadNetworkName(workload))}`);
	lines.push(`EnvironmentFile=${options.envFile}`);
	// Container root is not host root: every container gets its own range of the `containers`
	// subordinate ids (see userns.ts), so uid 0 inside maps to an unprivileged host uid. `U` hands
	// the writable mounts (and the 0400 secret files) to whichever uid the container runs as, on
	// each start, because an `auto` range is not guaranteed to be the same one next time.
	lines.push(`UserNS=${CONTAINER_USERNS}`);
	if (!runner) lines.push(`Volume=${options.dataDir}:/data:Z,U`);
	for (const mount of options.volumeMounts ?? []) {
		// A read-only attachment is never chowned: the volume's one writer owns it (single-writer),
		// and a reader re-owning it would take it away from that writer.
		lines.push(`Volume=${mount.hostPath}:${mount.mountPath}:${mount.readOnly ? 'ro,Z' : 'Z,U'}`);
	}
	if (options.secretsDir) {
		lines.push(`Volume=${options.secretsDir}:/run/skiff-secrets:ro,Z,U`);
		for (const secret of workload.secrets) {
			if (secret.delivery === 'file')
				lines.push(`Environment=${secret.name}_FILE=/run/skiff-secrets/${secret.name}`);
		}
	}
	if (options.identityDir) {
		// `U` hands the directory (and its 0400 token) to the container's own uid on every start,
		// because a rootless `auto` user namespace range is not guaranteed to be the same one next
		// time. Mounting the directory keeps an atomic token rewrite visible to the running app.
		lines.push(`Volume=${options.identityDir}:/var/run/skiff:ro,Z,U`);
	}
	lines.push('DropCapability=all');
	lines.push('NoNewPrivileges=true');
	// A runner writes its config and `_work` checkout under /home/runner; its root is a throwaway
	// layer recreated per job, which is the isolation boundary instead of a read-only root.
	if (!runner) {
		lines.push('ReadOnly=true');
		lines.push('Tmpfs=/tmp:rw,size=64m');
	}
	pushApparmor(lines, options.apparmorProfile);
	// `podman run --authfile` works on every Quadlet version, unlike a `.container` AuthFile= key.
	if (options.authFile) lines.push(`PodmanArgs=--authfile=${options.authFile}`);
	lines.push('');
	lines.push('[Service]');
	if (runner) {
		// The agent replaces a runner after each job with a new JIT config; systemd must not
		// restart it with the spent one. The first start pulls a large image.
		lines.push('Restart=no');
		lines.push('TimeoutStartSec=900');
	} else {
		lines.push('Restart=on-failure');
		lines.push('RestartSec=2');
	}
	lines.push(`MemoryMax=${workload.memoryMb}M`);
	lines.push(`CPUQuota=${cpuQuota(workload.cpus)}`);
	lines.push(`Slice=${WORKLOAD_SLICE}`);
	lines.push('');
	lines.push('[Install]');
	lines.push('WantedBy=default.target');
	return `${lines.join('\n')}\n`;
}

