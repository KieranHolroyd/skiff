/** Where a broker container reads its helper-written server config. */
export const BROKER_CONFIG_PATH = '/etc/skiff/broker.conf';

/**
 * NATS server config (docs/BROKERS.md §2). One ACL user with the owner password (no anonymous
 * access), JetStream on with its store in the `/data` mount, and both stores capped: memory at a
 * quarter of the unit's limit and the file store at the broker's storage budget, so a full broker
 * refuses publishes instead of filling the disk or being OOM-killed. Values are validated before
 * they reach the file, so nothing can inject another directive.
 */
export function renderNatsConfig(options: {
	id: string;
	user: string;
	password: string;
	memoryMb: number;
	storageMb: number;
}): string {
	if (!/^[a-z0-9_]{1,63}$/.test(options.user)) throw new ValidationError('Invalid broker user name');
	if (!/^[A-Za-z0-9_-]{16,200}$/.test(options.password))
		throw new ValidationError('The broker password must be base64url (16–200 characters)');
	if (!/^mq_[a-z0-9]{1,64}$/.test(options.id)) throw new ValidationError('Invalid broker id');
	const memoryStoreMb = Math.max(16, Math.floor(options.memoryMb * 0.25));
	return [
		'# Generated by skiff-helper. Do not edit; changes are overwritten.',
		`server_name: "${brokerAlias(options.id)}"`,
		// Auth is enforced below; the port is loopback/private-network only (D56).
		'listen: "0.0.0.0:4222"',
		'jetstream {',
		'  store_dir: "/data"',
		`  max_memory_store: ${memoryStoreMb}MB`,
		`  max_file_store: ${options.storageMb}MB`,
		'}',
		'authorization {',
		'  users: [',
		`    { user: "${options.user}", password: "${options.password}" }`,
		'  ]',
		'}',
		'',
	].join('\n');
}

/**
 * The fixed queue-broker profile (D111). Like the database profile, the image, user, mounts and
 * container port come from the helper's registry; only the host port, limits, env file and the
 * helper-written config come from the (validated) request. The client port is published on
 * loopback only: nothing listens on a public or WireGuard address (D56).
 */
export function renderBrokerUnit(options: {
	workload: WorkloadDesired;
	envFile: string;
	dataDir: string;
	serverConfigPath: string | null;
	apparmorProfile?: string | null;
}): string {
	const { workload } = options;
	const broker = workload.broker;
	if (!broker) throw new ValidationError('renderBrokerUnit needs a broker workload');
	if (!options.serverConfigPath) throw new ValidationError(`${broker.engine} needs its helper-written server config`);
	const info = BROKER_ENGINES[broker.engine];
	const lines: string[] = [];
	lines.push('[Unit]');
	lines.push(`Description=Skiff broker ${workload.id} (${workload.projectSlug}, ${broker.engine} ${broker.version})`);
	lines.push('After=network-online.target');
	lines.push('Wants=network-online.target');
	lines.push('StartLimitIntervalSec=300');
	lines.push('StartLimitBurst=10');
	lines.push('');
	lines.push('[Container]');
	lines.push(`ContainerName=skiff-workload-${workload.id}`);
	lines.push(`Image=${brokerImage(broker)}`);
	lines.push(`Exec=${['nats-server', '--config', BROKER_CONFIG_PATH].map(quoteSystemdArg).join(' ')}`);
	lines.push(`User=${info.uid}:${info.gid}`);
	lines.push(`PublishPort=127.0.0.1:${workload.port}:${info.containerPort}`);
	lines.push(`Network=${networkUnitName(workloadNetworkName(workload))}`);
	lines.push(`NetworkAlias=${brokerAlias(workload.id)}`);
	lines.push(`EnvironmentFile=${options.envFile}`);
	lines.push(`Volume=${options.dataDir}:/data:Z`);
	lines.push(`Volume=${options.serverConfigPath}:${BROKER_CONFIG_PATH}:ro,Z`);
	lines.push('Tmpfs=/tmp:rw,size=16m');
	lines.push('DropCapability=all');
	lines.push('NoNewPrivileges=true');
	lines.push('ReadOnly=true');
	pushApparmor(lines, options.apparmorProfile);
	lines.push('');
	lines.push('[Service]');
	lines.push('Restart=on-failure');
	lines.push('RestartSec=5');
	// The first start pulls the image; a clean stop lets JetStream flush its stores.
	lines.push('TimeoutStartSec=600');
	lines.push('TimeoutStopSec=60');
	lines.push(`MemoryMax=${workload.memoryMb}M`);
	lines.push(`CPUQuota=${cpuQuota(workload.cpus)}`);
	lines.push(`Slice=${WORKLOAD_SLICE}`);
	lines.push('');
	lines.push('[Install]');
	lines.push('WantedBy=default.target');
	return `${lines.join('\n')}\n`;
}

function cpuQuota(cpus: number): string {
	const percent = Math.max(1, Math.round(cpus * 100));
	return `${percent}%`;
}
