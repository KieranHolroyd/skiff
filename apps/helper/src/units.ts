/**
 * systemd's ExecStart parser understands double quotes and C escapes, plus `$`/`%` expansion.
 * Quote every argv element and escape the four characters that have meaning, so an argument that
 * looks like a variable is passed through literally. Newlines are already rejected by validation.
 */
export function quoteSystemdArg(arg: string): string {
	let quoted = '"';
	for (const char of arg) {
		if (char === '\\') quoted += '\\\\';
		else if (char === '"') quoted += '\\"';
		else if (char === '$') quoted += '$$';
		else if (char === '%') quoted += '%%';
		else quoted += char;
	}
	return `${quoted}"`;
}

/**
 * Absolute executables are invoked directly. A bare command (`bun`, `node`, `./bin/app`) goes
 * through `/usr/bin/env`, which is absolute, so no shell is involved and `PATH` still applies.
 */
export function renderExecStart(command: string[]): string {
	const [executable, ...args] = command;
	if (!executable) throw new ValidationError('command must not be empty');
	const rendered = command.map(quoteSystemdArg).join(' ');
	return executable.startsWith('/') ? rendered : `/usr/bin/env ${rendered}`;
}

/**
 * EnvironmentFile syntax: `KEY="value"` with C escapes inside double quotes. `$` is not expanded
 * in environment files, so only backslash, quote and control characters need escaping.
 */
export function escapeEnvValue(value: string): string {
	if (value.includes('\0')) throw new ValidationError('Environment values must not contain NUL bytes');
	let escaped = '';
	for (const char of value) {
		switch (char) {
			case '\\':
				escaped += '\\\\';
				break;
			case '"':
				escaped += '\\"';
				break;
			case '\n':
				escaped += '\\n';
				break;
			case '\r':
				escaped += '\\r';
				break;
			case '\t':
				escaped += '\\t';
				break;
			default: {
				const code = char.codePointAt(0) ?? 0;
				if (code < 0x20 || code === 0x7f) escaped += `\\x${code.toString(16).padStart(2, '0')}`;
				else escaped += char;
			}
		}
	}
	return `"${escaped}"`;
}

/**
 * Stable ordering makes the renderer idempotent. An empty value is written bare (`KEY=`), which
 * every parser reads as "set to the empty string".
 */
export function renderEnvFile(env: Record<string, string>): string {
	const lines = Object.keys(env)
		.sort()
		.map((name) => {
			const value = env[name] ?? '';
			return value === '' ? `${name}=` : `${name}=${escapeEnvValue(value)}`;
		});
	return lines.length === 0 ? '' : `${lines.join('\n')}\n`;
}

/**
 * Env file for Quadlet's `EnvironmentFile=`, which becomes `podman run --env-file`. Podman (like
 * Docker) takes everything after the first `=` literally: no quote stripping, no escapes. So the
 * systemd format above would hand a container `"value"` with the quotes. Values are written raw;
 * a line break cannot be represented and is refused (file secrets carry multi-line values).
 */
export function renderContainerEnvFile(env: Record<string, string>): string {
	const lines = Object.keys(env)
		.sort()
		.map((name) => {
			const value = env[name] ?? '';
			if (/[\r\n\0]/.test(value))
				throw new ValidationError(
					`Environment value ${name} contains a line break, which a container env file cannot carry; deliver it as a file secret`,
				);
			return `${name}=${value}`;
		});
	return lines.length === 0 ? '' : `${lines.join('\n')}\n`;
}

export interface UnitSecretFile {
	name: string;
	/** Absolute path to the 0400 file written by the helper. */
	path: string;
}

export interface ProcessUnitOptions {
	workload: WorkloadDesired;
	releaseDir: string;
	envFile: string;
	secrets: UnitSecretFile[];
	command: string[];
	/** Environment keys already present in the activation payload. */
	envNames: string[];
}

export function renderProcessUnit(options: ProcessUnitOptions): string {
	const { workload } = options;
	const lines: string[] = [];
	lines.push('# Generated by skiff-helper. Do not edit; changes are overwritten.');
	lines.push('[Unit]');
	lines.push(`Description=${description(workload)}`);
	lines.push('Documentation=https://github.com/kieranholroyd/private-cloud-deploys/blob/main/docs/DESIGN.md');
	lines.push('After=network-online.target');
	lines.push('Wants=network-online.target');
	lines.push('StartLimitIntervalSec=60');
	lines.push('StartLimitBurst=10');
	lines.push('');
	lines.push('[Service]');
	lines.push('Type=simple');
	lines.push('DynamicUser=yes');
	lines.push(`StateDirectory=skiff-workloads/${workload.id}`);
	lines.push('StateDirectoryMode=0700');
	lines.push(`WorkingDirectory=${options.releaseDir}`);
	lines.push(`EnvironmentFile=-${options.envFile}`);
	lines.push(`Environment=PATH=${DEFAULT_PATH}`);
	if (!workload.socketActivation) {
		if (!options.envNames.includes('PORT')) lines.push(`Environment=PORT=${workload.port}`);
		if (!options.envNames.includes('HOST')) lines.push('Environment=HOST=127.0.0.1');
	}
	for (const secret of options.secrets) {
		// systemd reads the file as the service manager; the unit sees it via $CREDENTIALS_DIRECTORY.
		lines.push(`LoadCredential=${secret.name}:${secret.path}`);
		lines.push(`Environment=${secret.name}_FILE=%d/${secret.name}`);
	}
	lines.push(`ExecStart=${renderExecStart(options.command)}`);
	lines.push('Restart=on-failure');
	lines.push('RestartSec=2');
	lines.push('TimeoutStopSec=30');
	lines.push('KillSignal=SIGTERM');
	lines.push(`MemoryMax=${workload.memoryMb}M`);
	lines.push(`CPUQuota=${cpuQuota(workload.cpus)}`);
	lines.push(`Slice=${WORKLOAD_SLICE}`);
	lines.push('NoNewPrivileges=yes');
	lines.push('ProtectSystem=strict');
	lines.push('ProtectHome=yes');
	lines.push('PrivateTmp=yes');
	lines.push('PrivateDevices=yes');
	lines.push('ProtectClock=yes');
	lines.push('ProtectHostname=yes');
	lines.push('ProtectKernelTunables=yes');
	lines.push('ProtectKernelModules=yes');
	lines.push('ProtectKernelLogs=yes');
	lines.push('ProtectControlGroups=yes');
	lines.push('RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK');
	lines.push('RestrictNamespaces=yes');
	lines.push('RestrictRealtime=yes');
	lines.push('RestrictSUIDSGID=yes');
	lines.push('LockPersonality=yes');
	lines.push('SystemCallArchitectures=native');
	lines.push('CapabilityBoundingSet=');
	lines.push('AmbientCapabilities=');
	lines.push('UMask=0077');
	if (!workload.socketActivation) {
		lines.push('');
		lines.push('[Install]');
		lines.push('WantedBy=multi-user.target');
	}
	return `${lines.join('\n')}\n`;
}

export interface SocketUnitOptions {
	workload: WorkloadDesired;
	socketPath: string;
	socketMode: string;
	socketGroup: string | null;
}

export function renderSocketUnit(options: SocketUnitOptions): string {
	const lines: string[] = [];
	lines.push('# Generated by skiff-helper. Do not edit; changes are overwritten.');
	lines.push('[Unit]');
	lines.push(`Description=${description(options.workload)} socket`);
	lines.push('');
	lines.push('[Socket]');
	lines.push(`ListenStream=${options.socketPath}`);
	lines.push(`SocketMode=${options.socketMode}`);
	if (options.socketGroup) lines.push(`SocketGroup=${options.socketGroup}`);
	lines.push('DirectoryMode=0755');
	lines.push('RemoveOnStop=yes');
	lines.push('');
	lines.push('[Install]');
	lines.push('WantedBy=sockets.target');
	return `${lines.join('\n')}\n`;
}

export interface ContainerUnitOptions {
	workload: WorkloadDesired;
	image: string;
	envFile: string;
	/** Host directory mounted at /data (persistent workload state). */
	dataDir: string;
	/** Host directory holding file secrets, mounted read-only when non-empty. */
	secretsDir: string | null;
}

/**
 * Quadlet `.container`. Quadlet turns this into `skiff-workload-<id>.service`; the `[Service]`
 * section carries the same slice/memory/CPU caps as a process unit.
 */
export function renderContainerUnit(options: ContainerUnitOptions): string {
	const { workload } = options;
	if (workload.database) return renderDatabaseUnit({ workload, envFile: options.envFile, dataDir: options.dataDir });
	if (workload.objectStorage) return renderStorageUnit({ workload, envFile: options.envFile, dataDir: options.dataDir });
	const lines: string[] = [];
	lines.push('[Unit]');
	lines.push(`Description=${description(workload)} (container)`);
	lines.push('After=network-online.target');
	lines.push('Wants=network-online.target');
	lines.push('StartLimitIntervalSec=60');
	lines.push('StartLimitBurst=10');
	lines.push('');
	lines.push('[Container]');
	lines.push(`ContainerName=skiff-workload-${workload.id}`);
	lines.push(`Image=${options.image}`);
	// Caddy on the host proxies to loopback; the container listens on the declared port.
	lines.push(`PublishPort=127.0.0.1:${workload.port}:${workload.port}`);
	lines.push(`Network=${WORKLOAD_NETWORK_UNIT}`);
	lines.push(`EnvironmentFile=${options.envFile}`);
	lines.push(`Volume=${options.dataDir}:/data:Z`);
	if (options.secretsDir) {
		lines.push(`Volume=${options.secretsDir}:/run/skiff-secrets:ro,Z`);
		for (const secret of workload.secrets) {
			if (secret.delivery === 'file')
				lines.push(`Environment=${secret.name}_FILE=/run/skiff-secrets/${secret.name}`);
		}
	}
	lines.push('DropCapability=all');
	lines.push('NoNewPrivileges=true');
	lines.push('ReadOnly=true');
	lines.push('Tmpfs=/tmp:rw,size=64m');
	lines.push('');
	lines.push('[Service]');
	lines.push('Restart=on-failure');
	lines.push('RestartSec=2');
	lines.push(`MemoryMax=${workload.memoryMb}M`);
	lines.push(`CPUQuota=${cpuQuota(workload.cpus)}`);
	lines.push(`Slice=${WORKLOAD_SLICE}`);
	lines.push('');
	lines.push('[Install]');
	lines.push('WantedBy=default.target');
	return `${lines.join('\n')}\n`;
}

export interface DatabaseUnitOptions {
	workload: WorkloadDesired;
	envFile: string;
	/** Host directory mounted at /data, created 0700 and owned by the engine's user. */
	dataDir: string;
}

/**
 * The fixed database profile (D55, D61). Image, user, mounts and the container port come from the
 * helper's registry; only the host port, limits and env file come from the (validated) request.
 * The port is published on loopback only: nothing listens on a public or WireGuard address (D56).
 */
export function renderDatabaseUnit(options: DatabaseUnitOptions): string {
	const { workload } = options;
	const database = workload.database;
	if (!database) throw new ValidationError('renderDatabaseUnit needs a database workload');
	const info = DATABASE_ENGINES[database.engine];
	const lines: string[] = [];
	lines.push('[Unit]');
	lines.push(`Description=Skiff database ${workload.id} (${workload.projectSlug}, ${database.engine} ${database.version})`);
	lines.push('After=network-online.target');
	lines.push('Wants=network-online.target');
	lines.push('StartLimitIntervalSec=300');
	lines.push('StartLimitBurst=10');
	lines.push('');
	lines.push('[Container]');
	lines.push(`ContainerName=skiff-workload-${workload.id}`);
	lines.push(`Image=${databaseImage(database)}`);
	lines.push(`User=${info.uid}:${info.gid}`);
	lines.push(`PublishPort=127.0.0.1:${workload.port}:${info.containerPort}`);
	lines.push(`Network=${WORKLOAD_NETWORK_UNIT}`);
	lines.push(`NetworkAlias=${databaseAlias(workload.id)}`);
	lines.push(`EnvironmentFile=${options.envFile}`);
	lines.push(`Volume=${options.dataDir}:/data:Z`);
	// The socket dir is created 3777 by the image; ReadOnly=true needs it (and /tmp) on tmpfs.
	lines.push('Tmpfs=/var/run/postgresql:rw,size=8m,mode=1777');
	lines.push('Tmpfs=/tmp:rw,size=64m');
	lines.push('DropCapability=all');
	lines.push('NoNewPrivileges=true');
	lines.push('ReadOnly=true');
	lines.push('');
	lines.push('[Service]');
	lines.push('Restart=on-failure');
	lines.push('RestartSec=5');
	// The first start pulls the image and runs initdb; a clean shutdown flushes WAL.
	lines.push('TimeoutStartSec=600');
	lines.push('TimeoutStopSec=120');
	lines.push(`MemoryMax=${workload.memoryMb}M`);
	lines.push(`CPUQuota=${cpuQuota(workload.cpus)}`);
	lines.push(`Slice=${WORKLOAD_SLICE}`);
	lines.push('');
	lines.push('[Install]');
	lines.push('WantedBy=default.target');
	return `${lines.join('\n')}\n`;
}

