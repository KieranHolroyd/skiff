/**
 * systemd's ExecStart parser understands double quotes and C escapes, plus `$`/`%` expansion.
 * Quote every argv element and escape the four characters that have meaning, so an argument that
 * looks like a variable is passed through literally. Newlines are already rejected by validation.
 */
export function quoteSystemdArg(arg: string): string {
	let quoted = '"';
	for (const char of arg) {
		if (char === '\\') quoted += '\\\\';
		else if (char === '"') quoted += '\\"';
		else if (char === '$') quoted += '$$';
		else if (char === '%') quoted += '%%';
		else quoted += char;
	}
	return `${quoted}"`;
}

/**
 * Absolute executables are invoked directly. A bare command (`bun`, `node`, `./bin/app`) goes
 * through `/usr/bin/env`, which is absolute, so no shell is involved and `PATH` still applies.
 */
export function renderExecStart(command: string[]): string {
	const [executable, ...args] = command;
	if (!executable) throw new ValidationError('command must not be empty');
	const rendered = command.map(quoteSystemdArg).join(' ');
	return executable.startsWith('/') ? rendered : `/usr/bin/env ${rendered}`;
}

/**
 * The value half of a double-quoted `Environment=` assignment. systemd expands `%` specifiers
 * there (not `$`), and the quotes take C escapes; control characters have no safe form.
 */
export function escapeUnitEnvironmentValue(value: string): string {
	let escaped = '';
	for (const char of value) {
		const code = char.codePointAt(0) ?? 0;
		if (code < 0x20 || code === 0x7f)
			throw new ValidationError('Environment values in a unit must not contain control characters');
		if (char === '\\') escaped += '\\\\';
		else if (char === '"') escaped += '\\"';
		else if (char === '%') escaped += '%%';
		else escaped += char;
	}
	return escaped;
}

/**
 * EnvironmentFile syntax: `KEY="value"` with C escapes inside double quotes. `$` is not expanded
 * in environment files, so only backslash, quote and control characters need escaping.
 */
export function escapeEnvValue(value: string): string {
	if (value.includes('\0')) throw new ValidationError('Environment values must not contain NUL bytes');
	let escaped = '';
	for (const char of value) {
		switch (char) {
			case '\\':
				escaped += '\\\\';
				break;
			case '"':
				escaped += '\\"';
				break;
			case '\n':
				escaped += '\\n';
				break;
			case '\r':
				escaped += '\\r';
				break;
			case '\t':
				escaped += '\\t';
				break;
			default: {
				const code = char.codePointAt(0) ?? 0;
				if (code < 0x20 || code === 0x7f) escaped += `\\x${code.toString(16).padStart(2, '0')}`;
				else escaped += char;
			}
		}
	}
	return `"${escaped}"`;
}

/**
 * Stable ordering makes the renderer idempotent. An empty value is written bare (`KEY=`), which
 * every parser reads as "set to the empty string".
 */
export function renderEnvFile(env: Record<string, string>): string {
	const lines = Object.keys(env)
		.sort()
		.map((name) => {
			const value = env[name] ?? '';
			return value === '' ? `${name}=` : `${name}=${escapeEnvValue(value)}`;
		});
	return lines.length === 0 ? '' : `${lines.join('\n')}\n`;
}

/**
 * Env file for Quadlet's `EnvironmentFile=`, which becomes `podman run --env-file`. Podman (like
 * Docker) takes everything after the first `=` literally: no quote stripping, no escapes. So the
 * systemd format above would hand a container `"value"` with the quotes. Values are written raw;
 * a line break cannot be represented and is refused (file secrets carry multi-line values).
 */
export function renderContainerEnvFile(env: Record<string, string>): string {
	const lines = Object.keys(env)
		.sort()
		.map((name) => {
			const value = env[name] ?? '';
			if (/[\r\n\0]/.test(value))
				throw new ValidationError(
					`Environment value ${name} contains a line break, which a container env file cannot carry; deliver it as a file secret`,
				);
			return `${name}=${value}`;
		});
	return lines.length === 0 ? '' : `${lines.join('\n')}\n`;
}

