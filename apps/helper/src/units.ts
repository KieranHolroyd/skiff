/**
 * AppArmor is disabled for a container only when the host needs it. Ubuntu 26.04 (and recent
 * kernels on 24.04/Debian 13) sets `kernel.apparmor_restrict_unprivileged_unconfined=1`; with
 * `NoNewPrivileges=true` the runtime's profile change becomes a stack (`containers-default//&crun`),
 * and the stock profile only allows signals to the unstacked peer. Postgres then cannot signal its
 * own checkpointer (`could not signal for checkpoint: Permission denied`) and never starts.
 * `apparmor=unconfined` is the documented per-container workaround; every other confinement
 * (no capabilities, no-new-privileges, read-only root) stays in place.
 */
function apparmorPodmanArgs(profile: string | null | undefined): string | null {
	if (!profile) return null;
	if (!/^[A-Za-z0-9_.-]+$/.test(profile))
		throw new ValidationError(`Unsafe AppArmor profile name: ${profile}`);
	return `PodmanArgs=--security-opt apparmor=${profile}`;
}

function pushApparmor(lines: string[], profile: string | null | undefined): void {
	const line = apparmorPodmanArgs(profile);
	if (line) lines.push(line);
}

/** PgBouncer config for one database. `auth_file` is the 0600 userlist written beside it. */
export function renderPoolerConfig(options: {
	databaseAlias: string;
	/** Absolute path inside the pooler container. */
	authFile: string;
	maxClientConn?: number;
	defaultPoolSize?: number;
	/** Database owner allowed to run `SHOW POOLS`/`SHOW STATS` for metrics. */
	adminUser?: string;
	/** Client-facing TLS files inside the pooler container (DB_TLS). */
	tls?: { certFile: string; keyFile: string } | null;
}): string {
	const maxClient = options.maxClientConn ?? 200;
	const poolSize = options.defaultPoolSize ?? 20;
	const admin =
		options.adminUser && /^[A-Za-z_][A-Za-z0-9_]{0,62}$/.test(options.adminUser)
			? `admin_users = ${options.adminUser}\n`
			: '';
	const tls = options.tls
		? `client_tls_sslmode = require\nclient_tls_cert_file = ${options.tls.certFile}\nclient_tls_key_file = ${options.tls.keyFile}\n`
		: '';
	return `[databases]
* = host=${options.databaseAlias} port=5432

[pgbouncer]
listen_addr = 0.0.0.0
listen_port = 6432
auth_type = scram-sha-256
auth_file = ${options.authFile}
${admin}${tls}pool_mode = transaction
max_client_conn = ${maxClient}
default_pool_size = ${poolSize}
reserve_pool_size = 5
server_reset_query = DISCARD ALL
ignore_startup_parameters = extra_float_digits
`;
}

/** PgBouncer `userlist.txt`: one `"user" "password"` line. */
export function renderPoolerUserlist(user: string, password: string): string {
	const quote = (value: string) => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
	return `${quote(user)} ${quote(password)}\n`;
}

/**
 * The pooler sidecar: loopback-only PublishPort, the database network, and config files mounted
 * read-only from the workload runtime dir. It runs as the image's uid 70 and has no capabilities.
 */
export function renderPoolerUnit(options: {
	workload: WorkloadDesired;
	configPath: string;
	userlistPath: string;
	/** Host TLS directory mounted read-only when the pooler terminates client TLS. */
	tlsDir?: string | null;
	/** AppArmor profile workaround for hosts with the stacked-profile kernel bug. */
	apparmorProfile?: string | null;
}): string {
	const { workload } = options;
	if (!workload.database || !workload.pooler)
		throw new ValidationError('renderPoolerUnit needs a database workload with a pooler port');
	const lines: string[] = [];
	lines.push('[Unit]');
	lines.push(`Description=Skiff database pooler ${workload.id} (${workload.projectSlug})`);
	lines.push('After=network-online.target');
	lines.push('Wants=network-online.target');
	lines.push('StartLimitIntervalSec=300');
	lines.push('StartLimitBurst=10');
	lines.push('');
	lines.push('[Container]');
	lines.push(`ContainerName=skiff-workload-${workload.id}-pool`);
	lines.push(`Image=${DATABASE_POOLER_IMAGE}`);
	lines.push('User=70:70');
	lines.push(`PublishPort=127.0.0.1:${workload.pooler.port}:6432`);
	lines.push(`Network=${networkUnitName(workloadNetworkName(workload))}`);
	lines.push(`NetworkAlias=${databaseAlias(workload.id)}-pool`);
	lines.push(`Volume=${options.configPath}:/etc/pgbouncer/pgbouncer.ini:ro,Z`);
	lines.push(`Volume=${options.userlistPath}:/etc/pgbouncer/userlist.txt:ro,Z`);
	if (options.tlsDir) lines.push(`Volume=${options.tlsDir}:/run/skiff-tls:ro,Z`);
	lines.push('DropCapability=all');
	lines.push('NoNewPrivileges=true');
	lines.push('ReadOnly=true');
	lines.push('Tmpfs=/tmp:rw,size=16m');
	pushApparmor(lines, options.apparmorProfile);
	lines.push('');
	lines.push('[Service]');
	lines.push('Restart=on-failure');
	lines.push('RestartSec=3');
	lines.push('TimeoutStartSec=120');
	lines.push('TimeoutStopSec=30');
	lines.push(`MemoryMax=64M`);
	lines.push(`CPUQuota=50%`);
	lines.push(`Slice=${WORKLOAD_SLICE}`);
	lines.push('');
	lines.push('[Install]');
	lines.push('WantedBy=default.target');
	return `${lines.join('\n')}\n`;
}

