/** The platform path the DBGate studio is served under (DBGate's `WEB_ROOT`). */
export function studioPath(name: string): string {
	return `/databases/${encodeURIComponent(name)}/studio/proxy`;
}

/**
 * The URL the dashboard loads the studio from (iframe and "open in new tab").
 *
 * The root must end in `/`: DBGate resolves its bundle relative to it. The query string is part of
 * the browser's cache key, so it steps around the `…/proxy/` → `…/proxy` 308 that older builds
 * served without cache headers. Browsers cached that permanent redirect, and replaying it against
 * the current `…/proxy` → `…/proxy/` redirect loops. DBGate ignores the parameter.
 */
export function studioFrameUrl(path: string): string {
	const root = path.endsWith('/') ? path : `${path}/`;
	return `${root}?skiff-studio=1`;
}

/** Join the upstream gateway path with the request's rest path and query string. */
export function studioUpstreamPath(
	webRoot: string,
	rest: string | undefined,
	search: string
): string {
	const root = webRoot.endsWith('/') ? webRoot.slice(0, -1) : webRoot;
	const path = (rest ?? '').replace(/^\/+/, '');
	return `${root}${path ? `/${path}` : '/'}${search}`;
}

/**
 * DBGate redirects to absolute URLs rooted at the internal gateway host. Rewrite those to the
 * platform path so the browser never learns the node's internal hostname. Relative and external
 * locations are left untouched.
 */
export function rewriteStudioLocation(location: string, host: string): string {
	let url: URL;
	try {
		url = new URL(location);
	} catch {
		return location;
	}
	// DBGate may include its own container port in an absolute redirect; the host is the routing
	// key, so compare the hostname rather than the origin. HTTPS is never generated by the gateway.
	if (url.protocol !== 'http:' || url.hostname !== host) return location;
	return `${url.pathname || '/'}${url.search}${url.hash}`;
}
