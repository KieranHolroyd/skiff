<script lang="ts">
	import type { Column, ObjectRef, SchemaChangeInput, StudioInfo } from '@skiff/studio/protocol';
	import { Button } from '#lib/components/ui/button/index.js';
	import { Checkbox } from '#lib/components/ui/checkbox/index.js';
	import * as Dialog from '#lib/components/ui/dialog/index.js';
	import { Input } from '#lib/components/ui/input/index.js';
	import { Label } from '#lib/components/ui/label/index.js';
	import * as NativeSelect from '#lib/components/ui/native-select/index.js';
	import {
		columnEditChanges,
		columnSpec,
		commonTypes,
		editDraft,
		emptyColumn,
		type ColumnDraft,
		type ColumnEditDraft
	} from './changes.js';

	/**
	 * Add a column, or edit one (name, type, nullability, default). Edits only send what changed:
	 * an `alter-column` on the old name, then a `rename-column`.
	 */
	let {
		open = $bindable(false),
		object,
		dialect,
		column = null,
		onsubmit
	}: {
		open?: boolean;
		object: ObjectRef;
		dialect: StudioInfo['capabilities']['dialect'];
		/** The column to edit; null adds one. */
		column?: Column | null;
		onsubmit: (changes: SchemaChangeInput[]) => void;
	} = $props();

	const uid = $props.id();
	/** One form for both: adding ignores `keep`, editing ignores `identity`. */
	type Draft = Omit<ColumnEditDraft, 'defaultMode'> & Pick<ColumnDraft, 'identity'> & { defaultMode: ColumnEditDraft['defaultMode'] };
	let draft = $state<Draft>({ ...emptyColumn() });
	let error = $state<string | null>(null);

	let wasOpen = false;
	$effect(() => {
		if (open && !wasOpen) {
			draft = column ? { ...editDraft(column), identity: false } : { ...emptyColumn() };
			error = null;
		}
		wasOpen = open;
	});

	const table = $derived(object.path.at(-1) ?? '');

	function submit(event: SubmitEvent) {
		event.preventDefault();
		const snapshot = $state.snapshot(draft) as Draft;
		if (column) {
			const result = columnEditChanges(object, column, snapshot);
			if (!result.ok) return void (error = result.error);
			if (result.value.length === 0) return void (error = 'Nothing has changed.');
			open = false;
			onsubmit(result.value);
		} else {
			const defaultMode = snapshot.defaultMode === 'keep' ? 'none' : snapshot.defaultMode;
			const result = columnSpec({ ...snapshot, defaultMode });
			if (!result.ok) return void (error = result.error);
			open = false;
			onsubmit([{ op: 'add-column', object, column: result.value }]);
		}
	}
</script>

<datalist id="types-{uid}">
	{#each commonTypes(dialect) as type (type)}<option value={type}></option>{/each}
</datalist>

<Dialog.Root bind:open>
	<Dialog.Content class="sm:max-w-lg">
		<form class="flex flex-col gap-4" onsubmit={submit}>
			<Dialog.Header>
				<Dialog.Title>{column ? `Edit column ${column.name}` : `Add a column to ${table}`}</Dialog.Title>
				<Dialog.Description>
					{column
						? 'Only what you change is sent. Changing a type converts the values already stored, which can fail.'
						: 'A NOT NULL column needs a default when the table already has rows.'}
				</Dialog.Description>
			</Dialog.Header>

			<div class="grid gap-3 sm:grid-cols-2">
				<div class="space-y-1.5">
					<Label for="col-name-{uid}">Name</Label>
					<Input id="col-name-{uid}" bind:value={draft.name} autocomplete="off" spellcheck={false} class="font-mono" />
				</div>
				<div class="space-y-1.5">
					<Label for="col-type-{uid}">Type</Label>
					<Input id="col-type-{uid}" bind:value={draft.type} list="types-{uid}" autocomplete="off" spellcheck={false} class="font-mono" placeholder="e.g. text" />
				</div>
			</div>

			<div class="flex flex-wrap items-center gap-x-5 gap-y-2">
				<div class="flex items-center gap-2">
					<Checkbox id="col-null-{uid}" bind:checked={draft.nullable} disabled={draft.identity} />
					<Label for="col-null-{uid}" class="font-normal">Allows NULL</Label>
				</div>
				{#if !column}
					<div class="flex items-center gap-2">
						<Checkbox id="col-identity-{uid}" bind:checked={draft.identity} />
						<Label for="col-identity-{uid}" class="font-normal">
							{dialect === 'postgres' ? 'Identity (generated by default)' : 'AUTO_INCREMENT'}
						</Label>
					</div>
				{/if}
			</div>

			<div class="space-y-1.5">
				<Label for="col-default-{uid}">Default</Label>
				{#if column?.default}
					<p class="text-xs text-muted-foreground">
						Now: <code class="font-mono break-all">{column.default}</code>
					</p>
				{/if}
				<div class="flex flex-wrap gap-2">
					{#if column}
						<NativeSelect.Root id="col-default-{uid}" size="sm" bind:value={draft.defaultMode}>
							<NativeSelect.Option value="keep">{column.default ? 'Keep it' : 'No default (keep)'}</NativeSelect.Option>
							{#if column.default}<NativeSelect.Option value="none">Remove the default</NativeSelect.Option>{/if}
							<NativeSelect.Option value="literal">A value</NativeSelect.Option>
							<NativeSelect.Option value="expression">An expression</NativeSelect.Option>
						</NativeSelect.Root>
					{:else}
						<NativeSelect.Root id="col-default-{uid}" size="sm" bind:value={draft.defaultMode} disabled={draft.identity}>
							<NativeSelect.Option value="none">No default</NativeSelect.Option>
							<NativeSelect.Option value="literal">A value</NativeSelect.Option>
							<NativeSelect.Option value="expression">An expression</NativeSelect.Option>
						</NativeSelect.Root>
					{/if}
					{#if draft.defaultMode === 'literal' || draft.defaultMode === 'expression'}
						<Input
							bind:value={draft.defaultText}
							aria-label="Default {draft.defaultMode === 'literal' ? 'value' : 'expression'}"
							autocomplete="off"
							spellcheck={false}
							class="h-8 min-w-0 flex-1 font-mono"
							placeholder={draft.defaultMode === 'literal' ? 'quoted for you' : 'now(), CURRENT_TIMESTAMP'}
						/>
					{/if}
				</div>
			</div>

			{#if error}<p class="text-xs text-destructive" role="alert">{error}</p>{/if}

			<Dialog.Footer>
				<Button type="button" variant="outline" onclick={() => (open = false)}>Cancel</Button>
				<Button type="submit">Review</Button>
			</Dialog.Footer>
		</form>
	</Dialog.Content>
</Dialog.Root>
