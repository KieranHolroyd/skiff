import {
	FUNCTION_HEALTH_PATH,
	FUNCTION_INTERNAL_HEADER,
	FUNCTION_INTERNAL_PREFIX,
	FUNCTION_INTERNAL_VALUE,
	functionModuleNameProblem,
} from '@skiff/contracts';

/**
 * Renderer for the workerd shim module (docs/FUNCTIONS.md §4.2, §4.4, §4.10).
 *
 * A function host loads exactly one Worker, and it is this shim: the shim is the first module in the
 * generated config, so it is workerd's main module and the target of the socket. It imports the
 * user's entry module, forwards public requests to its `fetch`, and exposes the internal routes the
 * node uses to deliver cron and queue work over the host socket. Caddy overwrites the internal
 * header on every public request, so a client can never reach those routes (§4.10, FN9).
 *
 * The output is plain ESM with no Node APIs: workerd loads it without `nodejs_compat`. It is
 * rendered fresh on every apply, so nothing here may depend on the clock or randomness.
 */

export interface RenderFunctionShimOptions {
	/** Module name of the user's entry module; must be one of the manifest's modules. */
	main: string;
}

/**
 * Render the `function-shim` module source for the entry module `main`.
 *
 * Throws a plain `Error` when `main` is not a safe relative module name: the helper and control
 * plane validate it first, but this renderer is the last stop before the name lands inside an import
 * specifier, so it refuses an absolute path, `..`, a quote, a backslash or a newline itself.
 */
export function renderFunctionShim(options: RenderFunctionShimOptions): string {
	const specifier = moduleSpecifier(options.main);

	return `// Skiff function shim: the main module of a function host.
// Generated by the agent from desired state and rewritten on every apply. Do not edit.
//
// The user's entry module is the Worker. This shim wraps it so the host can answer a cheap
// liveness probe and hand cron and queue work to the user's handlers over internal routes.
// Caddy overwrites the internal header on every public request, so a client can never reach
// them; the health path stays public and reveals nothing.

import user from ${specifier};

const HEALTH_PATH = ${jsString(FUNCTION_HEALTH_PATH)};
const INTERNAL_PREFIX = ${jsString(FUNCTION_INTERNAL_PREFIX)};
const SCHEDULED_PATH = ${jsString(`${FUNCTION_INTERNAL_PREFIX}scheduled`)};
const QUEUE_PATH = ${jsString(`${FUNCTION_INTERNAL_PREFIX}queue`)};
const INTERNAL_HEADER = ${jsString(FUNCTION_INTERNAL_HEADER)};
const INTERNAL_VALUE = ${jsString(FUNCTION_INTERNAL_VALUE)};
const CRON_HEADER = ${jsString('x-skiff-cron')};
const SCHEDULED_TIME_HEADER = ${jsString('x-skiff-scheduled-time')};
const QUEUE_HEADER = ${jsString('x-skiff-queue')};

// A default export that is not an object (a bare function, say) has no handlers; that is a 501,
// not a crash. This is the only place the shim reaches into the user module.
function handles(name) {
	return user !== null && typeof user === "object" && typeof user[name] === "function";
}

const JSON_HEADERS = { "content-type": "application/json", "cache-control": "no-store" };

function json(body, status) {
	return new Response(JSON.stringify(body), { status, headers: JSON_HEADERS });
}

function notFound() {
	return new Response("Not Found", { status: 404 });
}

function notImplemented(message) {
	return json({ error: message }, 501);
}

function methodNotAllowed() {
	return new Response("Method Not Allowed", { status: 405, headers: { allow: "POST" } });
}

async function deliverScheduled(request, env, ctx) {
	if (!handles("scheduled")) return notImplemented("this function has no scheduled handler");
	const cron = request.headers.get(CRON_HEADER) ?? "";
	const rawTime = request.headers.get(SCHEDULED_TIME_HEADER);
	const parsedTime = rawTime === null ? Number.NaN : Number(rawTime);
	const scheduledTime = Number.isFinite(parsedTime) ? parsedTime : Date.now();
	await user.scheduled({ cron, scheduledTime }, env, ctx);
	return new Response(null, { status: 204 });
}

async function deliverQueue(request, env, ctx) {
	if (!handles("queue")) return notImplemented("this function has no queue handler");
	let messages;
	try {
		messages = await request.json();
	} catch {
		return json({ error: "the queue batch body is not valid JSON" }, 400);
	}
	if (!Array.isArray(messages)) return json({ error: "the queue batch body must be a JSON array of messages" }, 400);
	// Cloudflare's per-message verdicts: an explicit ack()/retry() wins; otherwise a handler that
	// returns acks the batch and one that throws retries it. The agent applies the results.
	const verdicts = new Map();
	const decide = (id, outcome, options) => {
		const delay = Number(options?.delaySeconds);
		verdicts.set(id, Number.isFinite(delay) && delay >= 0 ? { id, outcome, delaySeconds: delay } : { id, outcome });
	};
	const wrapped = messages.map((message) => ({
		...message,
		ack() { decide(message.id, "ack"); },
		retry(options) { decide(message.id, "retry", options); },
	}));
	const batch = {
		queue: request.headers.get(QUEUE_HEADER) ?? "",
		messages: wrapped,
		ackAll() { for (const message of messages) decide(message.id, "ack"); },
		retryAll(options) { for (const message of messages) decide(message.id, "retry", options); },
	};
	let failure = null;
	try {
		await user.queue(batch, env, ctx);
	} catch (error) {
		failure = error instanceof Error ? error.message : String(error);
	}
	const results = messages.map((message) => verdicts.get(message.id) ?? { id: message.id, outcome: failure === null ? "ack" : "retry" });
	return json(failure === null ? { results } : { results, error: failure }, 200);
}

async function handleFetch(request, env, ctx) {
	const path = new URL(request.url).pathname;
	if (path === HEALTH_PATH && (request.method === "GET" || request.method === "HEAD")) {
		return new Response('{"ok":true}', { status: 200, headers: JSON_HEADERS });
	}
	if (path.startsWith(INTERNAL_PREFIX)) {
		if (request.headers.get(INTERNAL_HEADER) !== INTERNAL_VALUE) return notFound();
		if (path === SCHEDULED_PATH) {
			if (request.method !== "POST") return methodNotAllowed();
			return deliverScheduled(request, env, ctx);
		}
		if (path === QUEUE_PATH) {
			if (request.method !== "POST") return methodNotAllowed();
			return deliverQueue(request, env, ctx);
		}
		return notFound();
	}
	if (!handles("fetch")) return notImplemented("this function has no fetch handler");
	return user.fetch(request, env, ctx);
}

const shim = { fetch: handleFetch };

if (handles("scheduled")) {
	shim.scheduled = (controller, env, ctx) => user.scheduled(controller, env, ctx);
}
if (handles("queue")) {
	shim.queue = (batch, env, ctx) => user.queue(batch, env, ctx);
}

export default shim;

// Named exports (Durable Object classes, alternate entrypoints) pass through untouched.
export * from ${specifier};
`;
}

/**
 * `./<main>` as a JavaScript string literal. The module name is validated first; JSON escaping is
 * a correct JavaScript escape for every string, so no quote or control character can break out.
 */
function moduleSpecifier(main: string): string {
	const problem = functionModuleNameProblem(main);
	if (problem)
		throw new Error(`Function entry module ${JSON.stringify(main)} is not a safe relative specifier: ${problem}`);
	return jsString(`./${main}`);
}

function jsString(value: string): string {
	return JSON.stringify(value);
}
