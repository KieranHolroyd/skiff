import {
	FUNCTION_HEALTH_PATH,
	FUNCTION_INTERNAL_HEADER,
	FUNCTION_INTERNAL_PREFIX,
	FUNCTION_INTERNAL_VALUE,
} from '@skiff/contracts';

/**
 * The shim for a Python function host (D121, docs/FUNCTIONS.md §4.2).
 *
 * A JavaScript module cannot import a Python Worker, so on a Python host the shim is its own Worker
 * (`skiff-shim`) with one service binding, `USER`, to the user's Worker. It keeps the contract of the
 * JavaScript shim exactly — same health path, same internal routes and headers, same queue verdict
 * body — so the agent's watchdog, cron and queue consumer cannot tell the two apart:
 *
 * - public requests go to `env.USER.fetch(request)`;
 * - cron goes to `env.USER.scheduled({ cron, scheduledTime })`, a real `scheduled` event;
 * - a queue batch goes to `env.USER.queue(name, messages)`, a real `queue` event, and workerd's
 *   result (explicit acks, retries, ackAll, retryBatch) is turned back into per-message verdicts.
 *
 * `scheduled()` and `queue()` on a service binding need the experimental
 * `service_binding_extra_handlers` flag; the agent renders it on this Worker only.
 */
export function renderPythonFunctionShim(): string {
	return `// Skiff function shim for a Python Worker: the socket's Worker on this host.
// Generated by the agent from desired state and rewritten on every apply. Do not edit.
//
// The user's Python Worker is reached through the USER service binding. Caddy overwrites the
// internal header on every public request, so a client can never reach the internal routes.

const HEALTH_PATH = ${jsString(FUNCTION_HEALTH_PATH)};
const INTERNAL_PREFIX = ${jsString(FUNCTION_INTERNAL_PREFIX)};
const SCHEDULED_PATH = ${jsString(`${FUNCTION_INTERNAL_PREFIX}scheduled`)};
const QUEUE_PATH = ${jsString(`${FUNCTION_INTERNAL_PREFIX}queue`)};
const INTERNAL_HEADER = ${jsString(FUNCTION_INTERNAL_HEADER)};
const INTERNAL_VALUE = ${jsString(FUNCTION_INTERNAL_VALUE)};
const CRON_HEADER = "x-skiff-cron";
const SCHEDULED_TIME_HEADER = "x-skiff-scheduled-time";
const QUEUE_HEADER = "x-skiff-queue";

const JSON_HEADERS = { "content-type": "application/json", "cache-control": "no-store" };

function json(body, status) {
	return new Response(JSON.stringify(body), { status, headers: JSON_HEADERS });
}

function methodNotAllowed() {
	return new Response("Method Not Allowed", { status: 405, headers: { allow: "POST" } });
}

async function deliverScheduled(request, env) {
	const cron = request.headers.get(CRON_HEADER) ?? "";
	const rawTime = request.headers.get(SCHEDULED_TIME_HEADER);
	const parsedTime = rawTime === null ? Number.NaN : Number(rawTime);
	const scheduledTime = Number.isFinite(parsedTime) ? parsedTime : Date.now();
	const result = await env.USER.scheduled({ cron, scheduledTime: new Date(scheduledTime) });
	if (result.outcome !== "ok") return json({ error: "the scheduled handler failed (" + result.outcome + ")" }, 500);
	return new Response(null, { status: 204 });
}

// Per-message verdicts from workerd's queue result, with the JavaScript shim's precedence: an
// explicit ack()/retry() wins, then ackAll()/retryAll(), then the handler's own outcome (returned:
// ack; threw: retry).
function verdictsFromQueueResult(messages, result) {
	const explicit = new Map();
	for (const id of result.explicitAcks ?? []) explicit.set(id, { id, outcome: "ack" });
	for (const retry of result.retryMessages ?? []) {
		const delay = Number(retry.delaySeconds);
		explicit.set(retry.msgId, Number.isFinite(delay) && delay >= 0
			? { id: retry.msgId, outcome: "retry", delaySeconds: delay }
			: { id: retry.msgId, outcome: "retry" });
	}
	const batchDelay = Number(result.retryBatch?.delaySeconds);
	const batch = result.retryBatch?.retry
		? (Number.isFinite(batchDelay) && batchDelay >= 0 ? { outcome: "retry", delaySeconds: batchDelay } : { outcome: "retry" })
		: result.ackAll
			? { outcome: "ack" }
			: { outcome: result.outcome === "ok" ? "ack" : "retry" };
	return messages.map((message) => explicit.get(message.id) ?? { id: message.id, ...batch });
}

async function deliverQueue(request, env) {
	let messages;
	try {
		messages = await request.json();
	} catch {
		return json({ error: "the queue batch body is not valid JSON" }, 400);
	}
	if (!Array.isArray(messages)) return json({ error: "the queue batch body must be a JSON array of messages" }, 400);
	const queue = request.headers.get(QUEUE_HEADER) ?? "";
	const delivered = messages.map((message) => ({
		id: String(message.id),
		timestamp: new Date(message.timestamp ?? Date.now()),
		body: message.body,
		attempts: Number(message.attempts) || 1,
	}));
	const result = await env.USER.queue(queue, delivered);
	const results = verdictsFromQueueResult(messages, result);
	return json(result.outcome === "ok" ? { results } : { results, error: "the queue handler failed (" + result.outcome + ")" }, 200);
}

export default {
	async fetch(request, env) {
		const path = new URL(request.url).pathname;
		if (path === HEALTH_PATH && (request.method === "GET" || request.method === "HEAD")) {
			return new Response('{"ok":true}', { status: 200, headers: JSON_HEADERS });
		}
		if (path.startsWith(INTERNAL_PREFIX)) {
			if (request.headers.get(INTERNAL_HEADER) !== INTERNAL_VALUE) return new Response("Not Found", { status: 404 });
			if (path === SCHEDULED_PATH) {
				if (request.method !== "POST") return methodNotAllowed();
				return deliverScheduled(request, env);
			}
			if (path === QUEUE_PATH) {
				if (request.method !== "POST") return methodNotAllowed();
				return deliverQueue(request, env);
			}
			return new Response("Not Found", { status: 404 });
		}
		return env.USER.fetch(request);
	},
};
`;
}

function jsString(value: string): string {
	return JSON.stringify(value);
}
