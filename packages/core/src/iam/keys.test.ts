import { beforeEach, describe, expect, test } from 'bun:test';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createDb } from '@yoal/db';
import { createCore, type Core } from '../index.ts';
import { LocalObjectStore } from '../object-store.ts';
import {
	KEY_ROTATION_INTERVAL_MS,
	KEY_ROTATION_OVERLAP_MS,
	signingKeyRotationDecision,
} from './keys.ts';

/**
 * The signing-key ring (docs/IAM.md I15). The migration is applied by the real migrator in
 * production; this test applies the same DDL because `packages/db/src/migrations.ts` is generated
 * at build time and is deliberately not regenerated by this change.
 */
const dir = mkdtempSync(join(tmpdir(), 'yoal-signing-keys-'));
const opened = createDb({ path: ':memory:' });
opened.sqlite.exec(`
	CREATE TABLE IF NOT EXISTS signing_keys (
		kid TEXT PRIMARY KEY,
		alg TEXT NOT NULL DEFAULT 'ES256',
		purpose TEXT NOT NULL,
		public_jwk TEXT NOT NULL,
		private_sealed TEXT NOT NULL,
		state TEXT NOT NULL CHECK (state IN ('next','active','retired')),
		created_at INTEGER NOT NULL,
		activated_at INTEGER,
		retire_after INTEGER
	);
	CREATE INDEX IF NOT EXISTS signing_keys_purpose_state_idx ON signing_keys (purpose, state);
`);

let now = Date.parse('2026-11-08T12:00:00Z');
let core: Core;

function open(): Core {
	return createCore({
		db: opened.db,
		sqlite: opened.sqlite,
		version: '0.1.0',
		config: {
			dataDir: dir,
			platformOrigin: 'https://control.test',
			contentDomain: 'sites.test',
			objectStore: new LocalObjectStore(join(dir, 'objects'), 'https://control.test', 'object-secret-123'),
			masterKey: new Uint8Array(32).fill(7),
			siteCookieSecret: 'site-cookie-secret-123',
			objectStoreSecret: 'object-secret-123',
			desiredAgentVersion: '0.1.0',
			now: () => now,
		},
	});
}

beforeEach(() => {
	now = Date.parse('2026-11-08T12:00:00Z');
	opened.sqlite.exec('DELETE FROM signing_keys; DELETE FROM audit_log;');
	core = open();
});

function row(kid: string): {
	state: string;
	alg: string;
	purpose: string;
	public_jwk: string;
	private_sealed: string;
	retire_after: number | null;
	activated_at: number | null;
} {
	return opened.sqlite
		.query<
			{
				state: string;
				alg: string;
				purpose: string;
				public_jwk: string;
				private_sealed: string;
				retire_after: number | null;
				activated_at: number | null;
			},
			[string]
		>('SELECT state, alg, purpose, public_jwk, private_sealed, retire_after, activated_at FROM signing_keys WHERE kid = ?')
		.get(kid)!;
}

describe('signing-key ring', () => {
	test('ensure creates one ES256 key, seals the private JWK and publishes only the public half', async () => {
		const key = await core.ctx.signingKeys.ensure('sts');
		expect(key).toMatchObject({ purpose: 'sts', alg: 'ES256', state: 'active' });
		expect(key.kid).toMatch(/^k_/);
		expect(key.publicJwk).toMatchObject({ kty: 'EC', crv: 'P-256' });
		expect(key.publicJwk).not.toHaveProperty('d');

		const stored = row(key.kid);
		expect(stored.state).toBe('active');
		expect(stored.activated_at).toBe(now);
		expect(JSON.parse(stored.public_jwk)).not.toHaveProperty('d');
		const sealed = JSON.parse(stored.private_sealed) as { nonce?: string; ciphertext?: string };
		expect(sealed.nonce).toBeString();
		expect(sealed.ciphertext).toBeString();

		// ensure is idempotent and never mints a second active key.
		const again = await core.ctx.signingKeys.ensure('sts');
		expect(again.kid).toBe(key.kid);
		expect(opened.sqlite.query<{ n: number }, []>("SELECT COUNT(*) AS n FROM signing_keys WHERE purpose = 'sts'").get()!.n).toBe(1);
	});

	test('signs and verifies an ES256 JWT with the platform issuer, audience and expiry', async () => {
		await core.ctx.signingKeys.ensure('sts');
		const token = await core.ctx.signingKeys.sign(
			'sts',
			{ sub: 'sa_deployer', aud: 'https://api.test', org_id: 'org_1' },
			300,
		);
		const [header, payload] = token.split('.');
		expect(JSON.parse(Buffer.from(header!, 'base64url').toString())).toMatchObject({ alg: 'ES256', typ: 'JWT' });
		expect(JSON.parse(Buffer.from(payload!, 'base64url').toString())).toMatchObject({
			iss: 'https://control.test',
			sub: 'sa_deployer',
			aud: 'https://api.test',
			org_id: 'org_1',
			exp: Math.floor(now / 1000) + 300,
		});

		const claims = await core.ctx.signingKeys.verify('sts', token, { audience: 'https://api.test' });
		expect(claims).toMatchObject({ sub: 'sa_deployer', iss: 'https://control.test' });
		await expect(core.ctx.signingKeys.verify('sts', token, { audience: 'https://other.test' })).rejects.toThrow(
			/audience/,
		);

		now += 361_000;
		await expect(core.ctx.signingKeys.verify('sts', token, { audience: 'https://api.test' })).rejects.toThrow(
			/expired/,
		);
	});

	test('rejects a tampered signature and an unknown key id', async () => {
		await core.ctx.signingKeys.ensure('sts');
		const token = await core.ctx.signingKeys.sign('sts', { sub: 'sa_1', aud: 'https://api.test' }, 300);
		const [header, payload, signature] = token.split('.');
		const tampered = `${header}.${payload}.${Buffer.alloc(64).toString('base64url')}`;
		await expect(core.ctx.signingKeys.verify('sts', tampered)).rejects.toThrow(/signature/);

		const forgedHeader = Buffer.from(
			JSON.stringify({ alg: 'ES256', typ: 'JWT', kid: 'k_unknown' }),
		).toString('base64url');
		await expect(core.ctx.signingKeys.verify('sts', `${forgedHeader}.${payload}.${signature}`)).rejects.toThrow(
			/no signing key/i,
		);
	});

	test('rotate publishes next, promotes it, retires the old active and closes the JWKS window', async () => {
		const first = await core.ctx.signingKeys.ensure('sts');
		const oldToken = await core.ctx.signingKeys.sign('sts', { sub: 'sa_1', aud: 'https://api.test' }, 300);

		const firstRotation = await core.ctx.signingKeys.rotate('sts');
		expect(firstRotation.active.kid).toBe(first.kid);
		expect(firstRotation.next?.kid).not.toBe(first.kid);
		expect(firstRotation.retiredKid).toBeNull();
		expect(core.ctx.signingKeys.jwks('sts')).toHaveLength(2);

		const secondRotation = await core.ctx.signingKeys.rotate('sts');
		expect(secondRotation.active.kid).toBe(firstRotation.next!.kid);
		expect(secondRotation.next?.kid).not.toBe(firstRotation.next!.kid);
		expect(secondRotation.retiredKid).toBe(first.kid);

		const retired = row(first.kid);
		expect(retired.state).toBe('retired');
		expect(retired.retire_after).toBe(now + 60 * 60_000 + 24 * 60 * 60_000);
		expect(core.ctx.signingKeys.jwks('sts')).toHaveLength(3);

		// A token signed moments before rotation still verifies against the retired key.
		await expect(core.ctx.signingKeys.verify('sts', oldToken, { audience: 'https://api.test' })).resolves.toMatchObject({
			sub: 'sa_1',
		});

		// Signing now uses the promoted key, not the retired one.
		const live = await core.ctx.signingKeys.sign('sts', { sub: 'sa_2', aud: 'https://api.test' }, 60);
		expect(JSON.parse(Buffer.from(live.split('.')[0]!, 'base64url').toString()).kid).toBe(secondRotation.active.kid);

		now = retired.retire_after! + 1;
		const keys = core.ctx.signingKeys.jwks('sts');
		expect(keys).toHaveLength(2);
		expect(keys.map((key) => key.kid)).not.toContain(first.kid);
	});

	test('audits every rotation as iam.key.rotate', async () => {
		await core.ctx.signingKeys.rotate('sts');
		await core.ctx.signingKeys.rotate('sts');
		const rows = opened.sqlite
			.query<{ n: number }, []>("SELECT COUNT(*) AS n FROM audit_log WHERE action = 'iam.key.rotate'")
			.get()!;
		expect(rows.n).toBe(2);
	});

	test('publishes every purpose except pool:* in the shared JWKS', async () => {
		const sts = await core.ctx.signingKeys.ensure('sts');
		const pool = await core.ctx.signingKeys.ensure('pool:team-a');
		const all = core.ctx.signingKeys.jwksAll();
		expect(all.keys.map((key) => key.kid)).toContain(sts.kid);
		expect(all.keys.map((key) => key.kid)).not.toContain(pool.kid);
		expect(core.ctx.signingKeys.jwks('pool:team-a').map((key) => key.kid)).toContain(pool.kid);
	});
});

describe('signing-key rotation schedule', () => {
	const base = Date.parse('2026-11-08T12:00:00Z');
	const interval = KEY_ROTATION_INTERVAL_MS;
	const overlap = KEY_ROTATION_OVERLAP_MS;

	test('not due while the active key is young', () => {
		const decision = signingKeyRotationDecision({
			activeActivatedAt: base - 10 * 24 * 60 * 60_000,
			nextCreatedAt: null,
			now: base,
		});
		expect(decision).toMatchObject({ action: 'skip', due: false });
		expect(decision.reason).toMatch(/not due/);
	});

	test('publishes a next key in the overlap window before the interval ends', () => {
		const decision = signingKeyRotationDecision({
			activeActivatedAt: base - (interval - overlap),
			nextCreatedAt: null,
			now: base,
		});
		expect(decision).toMatchObject({ action: 'publish-next', due: true });
	});

	test('does not promote a next key that has not been public for the overlap', () => {
		const decision = signingKeyRotationDecision({
			activeActivatedAt: base - interval - 24 * 60 * 60_000,
			nextCreatedAt: base - overlap + 1,
			now: base,
		});
		expect(decision).toMatchObject({ action: 'skip', due: false });
		expect(decision.reason).toMatch(/full overlap/);
	});

	test('promotes after the active interval and the full overlap', () => {
		const decision = signingKeyRotationDecision({
			activeActivatedAt: base - interval - 24 * 60 * 60_000,
			nextCreatedAt: base - overlap,
			now: base,
		});
		expect(decision).toMatchObject({ action: 'promote', due: true });
	});

	test('ensures a ring with no keys and promotes a lone waiting next', () => {
		expect(
			signingKeyRotationDecision({ activeActivatedAt: null, nextCreatedAt: null, now: base }),
		).toMatchObject({ action: 'ensure', due: true });
		expect(
			signingKeyRotationDecision({ activeActivatedAt: null, nextCreatedAt: base - 1, now: base }),
		).toMatchObject({ action: 'promote', due: true });
	});

	test('keeps two usable keys during the publication overlap', async () => {
		const first = await core.ctx.signingKeys.ensure('sts');
		const published = await core.ctx.signingKeys.rotate('sts');
		expect(published.active.kid).toBe(first.kid);
		expect(published.next?.kid).not.toBe(first.kid);
		expect(published.retiredKid).toBeNull();
		expect(
			core.ctx.signingKeys.list('sts').filter((key) => key.state !== 'retired'),
		).toHaveLength(2);
	});
});
