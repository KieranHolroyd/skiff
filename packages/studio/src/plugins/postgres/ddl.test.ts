import { describe, expect, test } from 'bun:test';
import { schemaChangeSchema, StudioError, type ObjectRef, type SchemaChange, type SchemaChangeInput } from '../../protocol.ts';
import { columnDefinition, defaultSql, indexName, renderAlter, type AlterContext } from './ddl.ts';

const table: ObjectRef = { path: ['public', 'items'], kind: 'table' };
const TABLE: AlterContext = { relkind: 'r' };

function change(input: SchemaChangeInput): SchemaChange {
	return schemaChangeSchema.parse(input);
}

function render(input: SchemaChangeInput, context: AlterContext = TABLE): string[] {
	return renderAlter(change(input), context);
}

function refusal(fn: () => unknown): string | null {
	try {
		fn();
		return null;
	} catch (error) {
		return error instanceof StudioError ? error.code : 'other';
	}
}

describe('postgres ddl', () => {
	test('quotes every name, keeping case and doubling embedded quotes', () => {
		expect(render({ op: 'create-schema', name: 'Sales"; DROP' })).toEqual(['CREATE SCHEMA "Sales""; DROP"']);
		expect(render({ op: 'rename', object: { path: ['public', 'My"T'], kind: 'table' }, name: 'b' })).toEqual([
			'ALTER TABLE "public"."My""T" RENAME TO "b"',
		]);
	});

	test('create-table renders columns, identity, defaults and the primary key', () => {
		const [sql] = render({
			op: 'create-table',
			parent: ['public'],
			name: 'orders',
			columns: [
				{ name: 'id', type: 'bigint', nullable: false, identity: true },
				{ name: 'note', type: 'character varying(200)', default: { literal: "it's" } },
				{ name: 'at', type: 'timestamp with time zone', nullable: false, default: { expression: 'now()' } },
				{ name: 'tags', type: 'text[]' },
				{ name: 'paid', type: 'boolean', default: { literal: false } },
				{ name: 'total', type: 'numeric(10,2)', default: { literal: -1.5 } },
			],
			primaryKey: ['id'],
		});
		expect(sql).toBe(
			[
				'CREATE TABLE "public"."orders" (',
				'  "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
				`  "note" character varying(200) DEFAULT 'it''s',`,
				'  "at" timestamp with time zone NOT NULL DEFAULT now(),',
				'  "tags" text[],',
				'  "paid" boolean DEFAULT FALSE,',
				'  "total" numeric(10,2) DEFAULT -1.5,',
				'  PRIMARY KEY ("id")',
				')',
			].join('\n'),
		);
	});

	test('create-table needs a schema, unique columns and a known primary key', () => {
		const columns = [{ name: 'id', type: 'integer' }];
		expect(refusal(() => render({ op: 'create-table', parent: [], name: 't', columns }))).toBe('bad_request');
		expect(
			refusal(() => render({ op: 'create-table', parent: ['public'], name: 't', columns: [...columns, ...columns] })),
		).toBe('bad_request');
		expect(
			refusal(() => render({ op: 'create-table', parent: ['public'], name: 't', columns, primaryKey: ['nope'] })),
		).toBe('bad_request');
	});

	test('drop and rename pick the keyword from the relation kind, and cascade on request', () => {
		expect(render({ op: 'drop', object: table })).toEqual(['DROP TABLE "public"."items"']);
		expect(render({ op: 'drop', object: table, cascade: true }, { relkind: 'p' })).toEqual([
			'DROP TABLE "public"."items" CASCADE',
		]);
		expect(render({ op: 'drop', object: table }, { relkind: 'v' })).toEqual(['DROP VIEW "public"."items"']);
		expect(render({ op: 'drop', object: table }, { relkind: 'm' })).toEqual(['DROP MATERIALIZED VIEW "public"."items"']);
		expect(render({ op: 'drop', object: table }, { relkind: 'f' })).toEqual(['DROP FOREIGN TABLE "public"."items"']);
		expect(render({ op: 'drop', object: { path: ['old'], kind: 'schema' }, cascade: true }, { relkind: null })).toEqual([
			'DROP SCHEMA "old" CASCADE',
		]);
		expect(render({ op: 'rename', object: table, name: 'v2' }, { relkind: 'm' })).toEqual([
			'ALTER MATERIALIZED VIEW "public"."items" RENAME TO "v2"',
		]);
		expect(render({ op: 'rename', object: { path: ['old'], kind: 'schema' }, name: 'new' }, { relkind: null })).toEqual([
			'ALTER SCHEMA "old" RENAME TO "new"',
		]);
	});

	test('truncate is for tables only', () => {
		expect(render({ op: 'truncate', object: table })).toEqual(['TRUNCATE TABLE "public"."items"']);
		expect(refusal(() => render({ op: 'truncate', object: table }, { relkind: 'v' }))).toBe('unsupported');
	});

	test('column edits', () => {
		expect(render({ op: 'add-column', object: table, column: { name: 'qty', type: 'integer', nullable: false, default: { literal: 0 } } })).toEqual([
			'ALTER TABLE "public"."items" ADD COLUMN "qty" integer NOT NULL DEFAULT 0',
		]);
		expect(render({ op: 'drop-column', object: table, column: 'qty' })).toEqual([
			'ALTER TABLE "public"."items" DROP COLUMN "qty"',
		]);
		expect(render({ op: 'rename-column', object: table, column: 'qty', name: 'Quantity' })).toEqual([
			'ALTER TABLE "public"."items" RENAME COLUMN "qty" TO "Quantity"',
		]);
		expect(refusal(() => render({ op: 'add-column', object: table, column: { name: 'x', type: 'int' } }, { relkind: 'v' }))).toBe(
			'unsupported',
		);
	});

	test('alter-column changes only the parts given', () => {
		expect(render({ op: 'alter-column', object: table, column: 'qty', type: 'bigint' })).toEqual([
			'ALTER TABLE "public"."items"\n  ALTER COLUMN "qty" TYPE bigint USING "qty"::bigint',
		]);
		expect(
			render({ op: 'alter-column', object: table, column: 'qty', nullable: true, default: null }),
		).toEqual(['ALTER TABLE "public"."items"\n  ALTER COLUMN "qty" DROP NOT NULL,\n  ALTER COLUMN "qty" DROP DEFAULT']);
		expect(render({ op: 'alter-column', object: table, column: 'qty', nullable: false, default: { literal: 'x' } })).toEqual([
			`ALTER TABLE "public"."items"\n  ALTER COLUMN "qty" SET NOT NULL,\n  ALTER COLUMN "qty" SET DEFAULT 'x'`,
		]);
		expect(refusal(() => render({ op: 'alter-column', object: table, column: 'qty' }))).toBe('bad_request');
	});

	test('indexes: generated names, direction, unique, and constraint-backed drops', () => {
		expect(
			render({ op: 'create-index', object: table, columns: [{ name: 'a' }, { name: 'b', dir: 'desc' }], unique: true }),
		).toEqual(['CREATE UNIQUE INDEX "items_a_b_idx" ON "public"."items" ("a", "b" DESC)']);
		expect(render({ op: 'create-index', object: table, name: 'by_a', columns: [{ name: 'a' }] }, { relkind: 'm' })).toEqual([
			'CREATE INDEX "by_a" ON "public"."items" ("a")',
		]);
		expect(refusal(() => render({ op: 'create-index', object: table, columns: [{ name: 'a' }] }, { relkind: 'v' }))).toBe(
			'unsupported',
		);
		expect(render({ op: 'drop-index', object: table, name: 'by_a' }, { relkind: 'r', indexConstraint: null })).toEqual([
			'DROP INDEX "public"."by_a"',
		]);
		expect(render({ op: 'drop-index', object: table, name: 'items_pkey' }, { relkind: 'r', indexConstraint: 'items_pkey' })).toEqual([
			'ALTER TABLE "public"."items" DROP CONSTRAINT "items_pkey"',
		]);
	});

	test('generated index names fit in 63 bytes without splitting a character', () => {
		const name = indexName('t'.repeat(40), ['é'.repeat(30)]);
		expect(new TextEncoder().encode(name).length).toBeLessThanOrEqual(63);
		expect(name.endsWith('�')).toBe(false);
		expect(indexName('items', ['a'])).toBe('items_a_idx');
	});

	test('types and default expressions are re-checked, whatever the caller skipped', () => {
		const raw = (input: object) => renderAlter(input as SchemaChange, TABLE);
		expect(
			refusal(() =>
				raw({ op: 'add-column', object: table, column: { name: 'x', type: 'int; DROP TABLE x', nullable: true, identity: false } }),
			),
		).toBe('bad_request');
		expect(refusal(() => raw({ op: 'alter-column', object: table, column: 'x', type: 'text --' }))).toBe('bad_request');
		expect(refusal(() => raw({ op: 'alter-column', object: table, column: 'x', default: { expression: 'now()); DROP' } }))).toBe(
			'bad_request',
		);
		expect(refusal(() => defaultSql({ literal: Number.NaN }))).toBe('bad_request');
		expect(refusal(() => defaultSql({ literal: 'a\0b' }))).toBe('bad_request');
		// The protocol schema refuses them too.
		expect(schemaChangeSchema.safeParse({ op: 'alter-column', object: table, column: 'x', type: 'int)' }).success).toBe(false);
	});

	test('identity columns cannot also carry a default', () => {
		expect(
			refusal(() => columnDefinition({ name: 'id', type: 'integer', nullable: false, identity: true, default: { literal: 1 } })),
		).toBe('bad_request');
	});

	test('create-collection is not a Postgres change', () => {
		expect(refusal(() => render({ op: 'create-collection', name: 'c' }))).toBe('unsupported');
	});
});
