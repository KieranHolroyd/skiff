/**
 * DDL for the studio's structure edits (`alter`). Pure: the session looks up what the change
 * needs from the catalog (the relation's kind, the constraint behind an index) and passes it in.
 *
 * Names are always quoted. Column types and default expressions are interpolated as written,
 * which is safe only because the protocol admits nothing but plain type names and niladic
 * defaults; both patterns are checked again here so a caller that skipped the schema cannot
 * smuggle a statement through.
 */
import {
	COLUMN_TYPE_PATTERN,
	DEFAULT_EXPRESSION_PATTERN,
	StudioError,
	type ColumnDefault,
	type ColumnSpec,
	type ObjectRef,
	type SchemaChange,
} from '../../protocol.ts';
import { qualified, quoteIdent } from './sql.ts';

/** Postgres truncates longer identifiers (NAMEDATALEN - 1 bytes). */
export const MAX_IDENTIFIER_BYTES = 63;

/** What the session found in the catalog for the change's object. */
export interface AlterContext {
	/** `pg_class.relkind` of the object (`r`, `p`, `v`, `m`, `f`); null for schema-level changes. */
	relkind: string | null;
	/** For `drop-index`: the primary/unique/exclusion constraint that owns the index, if any. */
	indexConstraint?: string | null;
}

export function columnType(type: string): string {
	const trimmed = type.trim();
	if (!COLUMN_TYPE_PATTERN.test(trimmed))
		throw new StudioError('bad_request', `"${type.slice(0, 60)}" is not a plain column type.`);
	return trimmed;
}

export function defaultSql(value: ColumnDefault): string {
	if ('expression' in value) {
		const expression = value.expression.trim();
		if (!DEFAULT_EXPRESSION_PATTERN.test(expression))
			throw new StudioError('bad_request', `"${expression.slice(0, 60)}" is not an allowed default expression.`);
		return expression;
	}
	const literal = value.literal;
	if (typeof literal === 'boolean') return literal ? 'TRUE' : 'FALSE';
	if (typeof literal === 'number') {
		if (!Number.isFinite(literal)) throw new StudioError('bad_request', 'A numeric default must be finite.');
		return String(literal);
	}
	return stringLiteral(literal);
}

/** A standard SQL string (the session pins `standard_conforming_strings = on`). */
export function stringLiteral(text: string): string {
	if (text.includes('\0')) throw new StudioError('bad_request', 'A default cannot contain NUL.');
	return `'${text.replaceAll("'", "''")}'`;
}

export function columnDefinition(column: ColumnSpec): string {
	const parts = [quoteIdent(column.name), columnType(column.type)];
	if (column.identity) parts.push('GENERATED BY DEFAULT AS IDENTITY');
	if (!column.nullable) parts.push('NOT NULL');
	if (column.default !== undefined) {
		if (column.identity) throw new StudioError('bad_request', `Identity column "${column.name}" cannot have a default.`);
		parts.push(`DEFAULT ${defaultSql(column.default)}`);
	}
	return parts.join(' ');
}

/** `<table>_<col>_<col>_idx`, cut to Postgres' identifier limit on a character boundary. */
export function indexName(table: string, columns: readonly string[]): string {
	return truncateBytes(`${table}_${columns.join('_')}_idx`, MAX_IDENTIFIER_BYTES);
}

function truncateBytes(text: string, max: number): string {
	const encoder = new TextEncoder();
	if (encoder.encode(text).length <= max) return text;
	let out = '';
	let size = 0;
	for (const char of text) {
		const bytes = encoder.encode(char).length;
		if (size + bytes > max) break;
		out += char;
		size += bytes;
	}
	return out;
}

function relationPath(object: ObjectRef): { schema: string; name: string } {
	const [schema, name] = object.path;
	if (object.path.length !== 2 || !schema || !name)
		throw new StudioError('bad_request', `${object.path.join('.')} is not a table or view.`);
	return { schema, name };
}

function schemaPath(object: ObjectRef): string | null {
	return object.path.length === 1 ? (object.path[0] as string) : null;
}

/** The `ALTER …`/`DROP …` keyword for a relation kind. */
function relationKeyword(relkind: string | null): string {
	switch (relkind) {
		case 'r':
		case 'p':
			return 'TABLE';
		case 'v':
			return 'VIEW';
		case 'm':
			return 'MATERIALIZED VIEW';
		case 'f':
			return 'FOREIGN TABLE';
		default:
			throw new StudioError('not_found', 'No table or view by that name.');
	}
}

function requireColumns(relkind: string | null, what: string): void {
	if (relkind !== 'r' && relkind !== 'p' && relkind !== 'f')
		throw new StudioError('unsupported', `Only tables can ${what}.`);
}

/** The statements one structure edit runs, in order, inside one transaction. */
export function renderAlter(change: SchemaChange, context: AlterContext): string[] {
	switch (change.op) {
		case 'create-schema':
			return [`CREATE SCHEMA ${quoteIdent(change.name)}`];

		case 'create-table': {
			const [schema] = change.parent;
			if (change.parent.length !== 1 || !schema)
				throw new StudioError('bad_request', 'Pick the schema the table goes in.');
			const names = new Set<string>();
			for (const column of change.columns) {
				if (names.has(column.name)) throw new StudioError('bad_request', `Column "${column.name}" is listed twice.`);
				names.add(column.name);
			}
			for (const key of change.primaryKey)
				if (!names.has(key)) throw new StudioError('bad_request', `Primary key column "${key}" is not in the table.`);
			const lines = change.columns.map(columnDefinition);
			if (change.primaryKey.length > 0) lines.push(`PRIMARY KEY (${change.primaryKey.map(quoteIdent).join(', ')})`);
			return [`CREATE TABLE ${qualified(schema, change.name)} (\n  ${lines.join(',\n  ')}\n)`];
		}

		case 'create-collection':
			throw new StudioError('unsupported', 'Postgres has tables, not collections.');

		case 'rename': {
			const schema = schemaPath(change.object);
			if (schema !== null) return [`ALTER SCHEMA ${quoteIdent(schema)} RENAME TO ${quoteIdent(change.name)}`];
			const { schema: parent, name } = relationPath(change.object);
			return [`ALTER ${relationKeyword(context.relkind)} ${qualified(parent, name)} RENAME TO ${quoteIdent(change.name)}`];
		}

		case 'drop': {
			const cascade = change.cascade ? ' CASCADE' : '';
			const schema = schemaPath(change.object);
			if (schema !== null) return [`DROP SCHEMA ${quoteIdent(schema)}${cascade}`];
			const { schema: parent, name } = relationPath(change.object);
			return [`DROP ${relationKeyword(context.relkind)} ${qualified(parent, name)}${cascade}`];
		}

		case 'truncate': {
			const { schema, name } = relationPath(change.object);
			if (context.relkind !== 'r' && context.relkind !== 'p')
				throw new StudioError('unsupported', 'Only tables can be truncated.');
			return [`TRUNCATE TABLE ${qualified(schema, name)}`];
		}

		case 'add-column': {
			const { schema, name } = relationPath(change.object);
			requireColumns(context.relkind, 'gain columns');
			return [
				`ALTER ${relationKeyword(context.relkind)} ${qualified(schema, name)} ADD COLUMN ${columnDefinition(change.column)}`,
			];
		}

		case 'drop-column': {
			const { schema, name } = relationPath(change.object);
			requireColumns(context.relkind, 'drop columns');
			return [`ALTER ${relationKeyword(context.relkind)} ${qualified(schema, name)} DROP COLUMN ${quoteIdent(change.column)}`];
		}

		case 'rename-column': {
			const { schema, name } = relationPath(change.object);
			return [
				`ALTER ${relationKeyword(context.relkind)} ${qualified(schema, name)} RENAME COLUMN ${quoteIdent(change.column)} TO ${quoteIdent(change.name)}`,
			];
		}

		case 'alter-column': {
			const { schema, name } = relationPath(change.object);
			requireColumns(context.relkind, 'change columns');
			const column = quoteIdent(change.column);
			const actions: string[] = [];
			if (change.type !== undefined) {
				const type = columnType(change.type);
				actions.push(`ALTER COLUMN ${column} TYPE ${type} USING ${column}::${type}`);
			}
			if (change.nullable !== undefined) actions.push(`ALTER COLUMN ${column} ${change.nullable ? 'DROP' : 'SET'} NOT NULL`);
			if (change.default !== undefined)
				actions.push(
					change.default === null
						? `ALTER COLUMN ${column} DROP DEFAULT`
						: `ALTER COLUMN ${column} SET DEFAULT ${defaultSql(change.default)}`,
				);
			if (actions.length === 0) throw new StudioError('bad_request', 'Nothing to change on this column.');
			return [`ALTER ${relationKeyword(context.relkind)} ${qualified(schema, name)}\n  ${actions.join(',\n  ')}`];
		}

		case 'create-index': {
			const { schema, name } = relationPath(change.object);
			if (context.relkind !== 'r' && context.relkind !== 'p' && context.relkind !== 'm')
				throw new StudioError('unsupported', 'Only tables and materialized views can be indexed.');
			const index = change.name ?? indexName(name, change.columns.map((column) => column.name));
			const columns = change.columns.map((column) => `${quoteIdent(column.name)}${column.dir === 'desc' ? ' DESC' : ''}`);
			return [
				`CREATE ${change.unique ? 'UNIQUE ' : ''}INDEX ${quoteIdent(index)} ON ${qualified(schema, name)} (${columns.join(', ')})`,
			];
		}

		case 'drop-index': {
			const { schema, name } = relationPath(change.object);
			// An index behind a primary key, unique or exclusion constraint goes with its constraint.
			if (context.indexConstraint)
				return [
					`ALTER ${relationKeyword(context.relkind)} ${qualified(schema, name)} DROP CONSTRAINT ${quoteIdent(context.indexConstraint)}`,
				];
			return [`DROP INDEX ${qualified(schema, change.name)}`];
		}
	}
}
