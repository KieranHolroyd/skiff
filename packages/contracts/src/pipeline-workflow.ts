const PUSH_FILTER_KEYS = ['branches', 'branches-ignore', 'tags', 'tags-ignore', 'paths', 'paths-ignore'];
const PR_FILTER_KEYS = ['branches', 'branches-ignore', 'paths', 'paths-ignore', 'types'];

function refFilter(value: unknown, path: string, issues: Issues, keys: readonly string[]): PipelineRefFilter {
	const filter: PipelineRefFilter = { branches: null, branchesIgnore: null, tags: null, tagsIgnore: null, paths: null, pathsIgnore: null };
	if (value === undefined || value === null) return filter;
	if (!isMap(value)) {
		issues.add(path, `Expected a mapping of filters, got ${describe(value)}`);
		return filter;
	}
	checkKeys(value, keys, path, issues);
	const list = (key: string): string[] | null => {
		const items = stringList(value[key], join(path, key), issues);
		for (const pattern of items ?? []) {
			const bare = pattern.startsWith('!') ? pattern.slice(1) : pattern;
			if (!compileGlob(bare)) issues.add(join(path, key), `Invalid pattern '${pattern}'`);
		}
		return items;
	};
	filter.branches = list('branches');
	filter.branchesIgnore = list('branches-ignore');
	filter.tags = list('tags');
	filter.tagsIgnore = list('tags-ignore');
	filter.paths = list('paths');
	filter.pathsIgnore = list('paths-ignore');
	for (const kind of ['branches', 'tags', 'paths']) {
		if (value[kind] !== undefined && value[`${kind}-ignore`] !== undefined) {
			issues.add(path, `Use either ${kind} or ${kind}-ignore, not both (negate with '!' instead)`);
		}
	}
	return filter;
}

function dispatchInputs(value: unknown, path: string, issues: Issues): Record<string, PipelineDispatchInput> {
	if (value === undefined || value === null) return {};
	if (!isMap(value)) {
		issues.add(path, `Expected a mapping, got ${describe(value)}`);
		return {};
	}
	checkKeys(value, ['inputs'], path, issues);
	return inputDefinitions(value.inputs, join(path, 'inputs'), issues, 'dispatch');
}

/**
 * `inputs:` of `workflow_dispatch` or `workflow_call`. Called workflows only take string, boolean
 * and number inputs, and GitHub requires their `type`.
 */
function inputDefinitions(raw: unknown, inputsPath: string, issues: Issues, kind: 'dispatch' | 'call'): Record<string, PipelineDispatchInput> {
	const inputs: Record<string, PipelineDispatchInput> = {};
	if (raw === undefined || raw === null) return inputs;
	if (!isMap(raw)) {
		issues.add(inputsPath, `Expected a mapping, got ${describe(raw)}`);
		return inputs;
	}
	const types = kind === 'call' ? ['string', 'boolean', 'number'] : ['string', 'boolean', 'number', 'choice', 'environment'];
	for (const [name, def] of Object.entries(raw)) {
		const p = join(inputsPath, name);
		if (!IDENTIFIER.test(name)) issues.add(p, 'Input names start with a letter or _ and contain letters, digits, - and _');
		const spec = def ?? {};
		if (!isMap(spec)) {
			issues.add(p, `Expected a mapping, got ${describe(spec)}`);
			continue;
		}
		checkKeys(spec, kind === 'call' ? ['description', 'required', 'default', 'type'] : ['description', 'required', 'default', 'type', 'options'], p, issues);
		if (kind === 'call' && spec.type === undefined) {
			issues.add(join(p, 'type'), 'workflow_call inputs need a type (string, boolean or number)');
			continue;
		}
		const type = spec.type ?? 'string';
		if (typeof type !== 'string' || !types.includes(type)) {
			issues.add(join(p, 'type'), `Unknown input type '${String(type)}' (${types.join(', ')})`);
			continue;
		}
		if (type !== 'string' && type !== 'boolean' && type !== 'number' && type !== 'choice' && type !== 'environment') continue;
		const options = kind === 'dispatch' ? (stringList(spec.options, join(p, 'options'), issues) ?? []) : [];
		if (type === 'choice' && options.length === 0) issues.add(join(p, 'options'), 'A choice input needs options');
		if (kind === 'dispatch' && type !== 'choice' && spec.options !== undefined) issues.add(join(p, 'options'), 'options only apply to choice inputs');
		let fallback: string | number | boolean | null = null;
		const rawDefault = spec.default;
		if (rawDefault !== undefined && rawDefault !== null) {
			const coerced = coerceInput(type, options, rawDefault);
			if (coerced.error !== undefined) issues.add(join(p, 'default'), coerced.error);
			else fallback = coerced.value;
		}
		inputs[name] = {
			type,
			description: optionalString(spec.description, join(p, 'description'), issues),
			required: booleanValue(spec.required, join(p, 'required'), issues, false),
			default: fallback,
			options,
		};
	}
	return inputs;
}

const KNOWN_UNSUPPORTED_EVENTS = 'supported: push, pull_request, workflow_dispatch, schedule, workflow_call, skiff_event';

/** `<source>.<event>` as in docs/EVENTS.md (`deployments.failed`, `storage.object-create`). */
const SKIFF_EVENT_TYPE = /^[a-z][a-z0-9-]*\.[a-z][a-z0-9-]*$/;
const SECRET_NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;

function workflowCallValue(value: unknown, path: string, issues: Issues): PipelineWorkflowCall {
	const out: PipelineWorkflowCall = { inputs: {}, outputs: {}, secrets: {} };
	if (value === undefined || value === null) return out;
	if (!isMap(value)) {
		issues.add(path, `Expected a mapping, got ${describe(value)}`);
		return out;
	}
	checkKeys(value, ['inputs', 'outputs', 'secrets'], path, issues);
	out.inputs = inputDefinitions(value.inputs, join(path, 'inputs'), issues, 'call');
	const outputsPath = join(path, 'outputs');
	if (value.outputs !== undefined && value.outputs !== null) {
		if (!isMap(value.outputs)) issues.add(outputsPath, `Expected a mapping, got ${describe(value.outputs)}`);
		else {
			for (const [name, def] of Object.entries(value.outputs)) {
				const p = join(outputsPath, name);
				if (!IDENTIFIER.test(name)) issues.add(p, 'Output names start with a letter or _ and contain letters, digits, - and _');
				if (!isMap(def)) {
					issues.add(p, 'Expected { value, description }');
					continue;
				}
				checkKeys(def, ['value', 'description'], p, issues);
				const outputValue = optionalString(def.value, join(p, 'value'), issues);
				if (outputValue === null) {
					issues.add(join(p, 'value'), 'value is required (e.g. ${{ jobs.build.outputs.digest }})');
					continue;
				}
				checkTemplates(jobsAsNeeds(outputValue), join(p, 'value'), issues, W.callOutputs);
				out.outputs[name] = { value: outputValue, description: optionalString(def.description, join(p, 'description'), issues) };
			}
		}
	}
	const secretsPath = join(path, 'secrets');
	if (value.secrets !== undefined && value.secrets !== null) {
		if (!isMap(value.secrets)) issues.add(secretsPath, `Expected a mapping, got ${describe(value.secrets)}`);
		else {
			for (const [name, def] of Object.entries(value.secrets)) {
				const p = join(secretsPath, name);
				if (!SECRET_NAME.test(name)) issues.add(p, 'Secret names are letters, digits and underscores');
				const spec = def ?? {};
				if (!isMap(spec)) {
					issues.add(p, 'Expected { required, description }');
					continue;
				}
				checkKeys(spec, ['required', 'description'], p, issues);
				out.secrets[name] = {
					required: booleanValue(spec.required, join(p, 'required'), issues, false),
					description: optionalString(spec.description, join(p, 'description'), issues),
				};
			}
		}
	}
	return out;
}

function skiffEventValue(value: unknown, path: string, issues: Issues): { types: string[] } {
	if (value === undefined || value === null) return { types: [] };
	if (!isMap(value)) {
		issues.add(path, `Expected { types: [...] }, got ${describe(value)}`);
		return { types: [] };
	}
	checkKeys(value, ['types'], path, issues);
	const types = stringList(value.types, join(path, 'types'), issues) ?? [];
	for (const type of types) {
		if (!SKIFF_EVENT_TYPE.test(type)) issues.add(join(path, 'types'), `'${type}' is not an event type; use <source>.<event>, e.g. deployments.failed (docs/EVENTS.md)`);
	}
	return { types: [...new Set(types)] };
}

/**
 * The `jobs` context only exists in `on.workflow_call.outputs`, and the expression engine has no
 * such context; `jobs.<id>` has the same shape as `needs.<id>`, so it is linted and evaluated as
 * that (`workflowCallOutputs`).
 */
function jobsAsNeeds(value: string): string {
	return value.replace(/(?<![\w.'"-])jobs(?=\s*[.[])/g, 'needs');
}

function triggers(value: unknown, path: string, issues: Issues): PipelineTriggers {
	const out: PipelineTriggers = { push: null, pullRequest: null, workflowDispatch: null, schedule: [], workflowCall: null, skiffEvent: null };
	let entries: [string, unknown][] = [];
	if (value === undefined || value === null) {
		issues.add(path, `on is required (${KNOWN_UNSUPPORTED_EVENTS})`);
		return out;
	}
	if (typeof value === 'string') entries = [[value, null]];
	else if (Array.isArray(value)) {
		value.forEach((item, index) => {
			if (typeof item === 'string') entries.push([item, null]);
			else issues.add(`${path}[${index}]`, `Expected an event name, got ${describe(item)}`);
		});
	} else if (isMap(value)) entries = Object.entries(value);
	else issues.add(path, `Expected an event name, a list or a mapping, got ${describe(value)}`);
	if (entries.length === 0 && isMap(value)) issues.add(path, 'Declare at least one trigger');
	for (const [event, config] of entries) {
		const p = join(path, event);
		switch (event) {
			case 'push':
				out.push = refFilter(config, p, issues, PUSH_FILTER_KEYS);
				break;
			case 'pull_request': {
				const filter = refFilter(config, p, issues, PR_FILTER_KEYS);
				let types = PR_DEFAULT_TYPES;
				if (isMap(config) && config.types !== undefined) {
					types = stringList(config.types, join(p, 'types'), issues) ?? [];
					for (const type of types) if (!PR_TYPES.has(type)) issues.add(join(p, 'types'), `Unknown pull_request type '${type}'`);
				}
				out.pullRequest = { ...filter, types };
				break;
			}
			case 'workflow_dispatch':
				out.workflowDispatch = { inputs: dispatchInputs(config, p, issues) };
				break;
			case 'workflow_call':
				out.workflowCall = workflowCallValue(config, p, issues);
				break;
			case 'skiff_event':
				out.skiffEvent = skiffEventValue(config, p, issues);
				break;
			case 'schedule': {
				if (!Array.isArray(config) || config.length === 0) {
					issues.add(p, 'schedule needs a list of { cron: "…" } entries');
					break;
				}
				config.forEach((entry, index) => {
					const ep = `${p}[${index}]`;
					if (!isMap(entry)) {
						issues.add(ep, 'Expected { cron: "…" }');
						return;
					}
					checkKeys(entry, ['cron'], ep, issues);
					if (typeof entry.cron !== 'string') {
						issues.add(join(ep, 'cron'), 'cron is required');
						return;
					}
					try {
						parseCron(entry.cron);
						out.schedule.push(entry.cron);
					} catch (error) {
						issues.add(join(ep, 'cron'), (error as Error).message);
					}
				});
				break;
			}
			default:
				issues.add(p, `The '${event}' trigger is not supported by Skiff Pipelines (${KNOWN_UNSUPPORTED_EVENTS})`);
		}
	}
	return out;
}

