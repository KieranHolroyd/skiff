// --- where expressions may appear ---------------------------------------------------------

/**
 * Which contexts and functions an expression may use, by location. A simplified version of
 * GitHub's context-availability table: contexts that do not exist yet at that point of planning
 * (`matrix` before expansion, `steps` before a job runs) are rejected at lint time instead of
 * silently evaluating to null.
 */
interface Where {
	contexts: ReadonlySet<string>;
	/** `hashFiles()` needs a workspace, so only steps (and job outputs) may call it. */
	hashFiles: boolean;
	/** Status functions belong in `if:`. */
	status: boolean;
}

const where = (contexts: string[], extra: Partial<Omit<Where, 'contexts'>> = {}): Where => ({
	contexts: new Set(contexts),
	hashFiles: extra.hashFiles ?? false,
	status: extra.status ?? false,
});

const JOB_STATIC = ['skiff', 'needs', 'strategy', 'matrix', 'vars', 'inputs'];
const STEP_ALL = [...JOB_STATIC, 'job', 'runner', 'env', 'secrets', 'steps'];

const W = {
	workflow: where(['skiff', 'inputs', 'vars']),
	workflowEnv: where(['skiff', 'inputs', 'vars', 'secrets']),
	jobIf: where(['skiff', 'needs', 'vars', 'inputs'], { status: true }),
	strategy: where(['skiff', 'needs', 'vars', 'inputs']),
	job: where(JOB_STATIC),
	jobEnv: where([...JOB_STATIC, 'secrets']),
	jobDefaults: where([...JOB_STATIC, 'env']),
	jobOutputs: where(STEP_ALL, { hashFiles: true }),
	environmentUrl: where(STEP_ALL.filter((name) => name !== 'secrets')),
	containerEnv: where([...JOB_STATIC, 'job', 'runner', 'env', 'secrets']),
	step: where(STEP_ALL, { hashFiles: true }),
	/** GitHub does not expose `secrets` to `if:` (use an env var instead). */
	stepIf: where(
		STEP_ALL.filter((name) => name !== 'secrets'),
		{ hashFiles: true, status: true },
	),
	/** `jobs.<id>.with` of a reusable-workflow call. */
	callWith: where(JOB_STATIC),
	callSecrets: where([...JOB_STATIC, 'secrets']),
	/** `on.workflow_call.outputs.*.value` (`jobs` is linted as `needs`, see jobsAsNeeds). */
	callOutputs: where(['skiff', 'inputs', 'vars', 'needs']),
};

// --- issue collection and small readers -----------------------------------------------------

class Issues {
	readonly list: PipelineWorkflowIssue[] = [];

	add(path: string, message: string): void {
		this.list.push({ path, message });
	}
}

const isMap = (value: unknown): value is Record<string, unknown> =>
	typeof value === 'object' && value !== null && !Array.isArray(value);

const join = (path: string, key: string): string => (path ? `${path}.${key}` : key);

function describe(value: unknown): string {
	if (value === null || value === undefined) return 'nothing';
	if (Array.isArray(value)) return 'a list';
	return typeof value === 'object' ? 'a mapping' : `a ${typeof value}`;
}

function checkKeys(value: Record<string, unknown>, allowed: readonly string[], path: string, issues: Issues, hints: Record<string, string> = {}): void {
	for (const key of Object.keys(value)) {
		if (allowed.includes(key)) continue;
		issues.add(join(path, key), hints[key] ?? `Unknown key '${key}' (allowed: ${allowed.join(', ')})`);
	}
}

/** A scalar as GitHub stringifies it for env/with values; null → ''. */
function scalar(value: unknown, path: string, issues: Issues): string | null {
	if (value === null || value === undefined) return '';
	if (typeof value === 'string') return value;
	if (typeof value === 'number' || typeof value === 'boolean') return stringifyExpressionValue(value);
	issues.add(path, `Expected a string, number or boolean, got ${describe(value)}`);
	return null;
}

function optionalString(value: unknown, path: string, issues: Issues): string | null {
	if (value === undefined || value === null) return null;
	if (typeof value === 'string') return value;
	if (typeof value === 'number' || typeof value === 'boolean') return stringifyExpressionValue(value);
	issues.add(path, `Expected a string, got ${describe(value)}`);
	return null;
}

/** `x` or `[x, y]` → string list; null when absent. */
function stringList(value: unknown, path: string, issues: Issues): string[] | null {
	if (value === undefined || value === null) return null;
	const items = Array.isArray(value) ? value : [value];
	const out: string[] = [];
	items.forEach((item, index) => {
		const itemPath = Array.isArray(value) ? `${path}[${index}]` : path;
		if (typeof item === 'string' || typeof item === 'number' || typeof item === 'boolean') {
			const text = stringifyExpressionValue(item);
			if (text.trim() === '') issues.add(itemPath, 'Must not be empty');
			else out.push(text);
		} else {
			issues.add(itemPath, `Expected a string, got ${describe(item)}`);
		}
	});
	return out;
}

function booleanValue(value: unknown, path: string, issues: Issues, fallback: boolean): boolean {
	if (value === undefined || value === null) return fallback;
	if (typeof value === 'boolean') return value;
	if (value === 'true' || value === 'false') return value === 'true';
	issues.add(path, hasTemplate(String(value)) ? 'Expressions are not supported here; use true or false' : `Expected true or false, got ${describe(value)}`);
	return fallback;
}

/** Validate every `${{ }}` in a string: it parses, and only uses contexts/functions allowed here. */
function checkTemplates(value: string, path: string, issues: Issues, at: Where): void {
	if (!hasTemplate(value)) return;
	let expressions: string[];
	try {
		expressions = extractExpressions(value);
	} catch (error) {
		issues.add(path, (error as Error).message);
		return;
	}
	for (const expr of expressions) checkExpression(expr, path, issues, at);
}

function checkExpression(expr: string, path: string, issues: Issues, at: Where): void {
	let references: string[];
	let functions: string[];
	try {
		references = expressionReferences(expr);
		functions = expressionFunctions(expr);
	} catch (error) {
		if (!(error instanceof PipelineExpressionError)) throw error;
		issues.add(path, error.message);
		return;
	}
	for (const name of references) {
		if (!at.contexts.has(name)) {
			issues.add(path, `Context '${name}' is not available here (available: ${[...at.contexts].join(', ')})`);
		}
	}
	for (const name of functions) {
		if (name === 'hashfiles' && !at.hashFiles) issues.add(path, 'hashFiles() is only available in steps');
		if (['success', 'failure', 'always', 'cancelled'].includes(name) && !at.status) {
			issues.add(path, `${name}() is only available in if: conditions`);
		}
	}
}

/** Recursively check templates in nested values (matrix entries). */
function checkTemplatesDeep(value: unknown, path: string, issues: Issues, at: Where): boolean {
	if (typeof value === 'string') {
		checkTemplates(value, path, issues, at);
		return hasTemplate(value);
	}
	let found = false;
	if (Array.isArray(value)) value.forEach((item, index) => (found = checkTemplatesDeep(item, `${path}[${index}]`, issues, at) || found));
	else if (isMap(value)) for (const [key, item] of Object.entries(value)) found = checkTemplatesDeep(item, join(path, key), issues, at) || found;
	return found;
}

function templateMap(value: unknown, path: string, issues: Issues, at: Where, envNames = false): TemplateMap {
	const out: TemplateMap = {};
	if (value === undefined || value === null) return out;
	if (!isMap(value)) {
		issues.add(path, `Expected a mapping, got ${describe(value)}`);
		return out;
	}
	for (const [key, raw] of Object.entries(value)) {
		const itemPath = join(path, key);
		if (envNames && (key === '' || /[=\0]/.test(key))) issues.add(itemPath, 'Not a valid environment variable name');
		const text = scalar(raw, itemPath, issues);
		if (text === null) continue;
		checkTemplates(text, itemPath, issues, at);
		out[key] = text;
	}
	return out;
}

/** `if:` → the bare expression (wrapper stripped), or null for "no condition". */
function condition(value: unknown, path: string, issues: Issues, at: Where): string | null {
	if (value === undefined || value === null) return null;
	if (typeof value !== 'string' && typeof value !== 'boolean' && typeof value !== 'number') {
		issues.add(path, `Expected an expression, got ${describe(value)}`);
		return null;
	}
	const text = String(value).trim();
	if (text === '') return null;
	let expr: string | null;
	try {
		expr = hasTemplate(text) ? unwrapExpression(text) : text;
	} catch (error) {
		issues.add(path, (error as Error).message);
		return text;
	}
	if (expr === null) {
		// Text mixed with templates is a non-empty string, i.e. always true (a classic GitHub trap).
		issues.add(path, 'Wrap the whole condition in one ${{ }} (or none): text around a template makes it always true');
		return text;
	}
	checkExpression(expr, path, issues, at);
	return expr.trim();
}

/** `python` is accepted in composite actions (third-party code, and the step runner knows it). */
function shellValue(value: unknown, path: string, issues: Issues, allowPython = false): string | null {
	const shell = optionalString(value, path, issues);
	if (shell === null) return null;
	if (shell === 'bash' || shell === 'sh' || shell.includes('{0}') || (allowPython && shell === 'python')) return shell;
	issues.add(path, `Unsupported shell '${shell}'; use bash, sh, or a custom command containing {0}`);
	return shell;
}

function defaultsValue(value: unknown, path: string, issues: Issues, at: Where): { shell: string | null; workingDirectory: string | null } {
	const out = { shell: null as string | null, workingDirectory: null as string | null };
	if (value === undefined || value === null) return out;
	if (!isMap(value)) {
		issues.add(path, `Expected a mapping, got ${describe(value)}`);
		return out;
	}
	checkKeys(value, ['run'], path, issues);
	const run = value.run;
	if (run === undefined || run === null) return out;
	const runPath = join(path, 'run');
	if (!isMap(run)) {
		issues.add(runPath, `Expected a mapping, got ${describe(run)}`);
		return out;
	}
	checkKeys(run, ['shell', 'working-directory'], runPath, issues);
	out.shell = shellValue(run.shell, join(runPath, 'shell'), issues);
	out.workingDirectory = optionalString(run['working-directory'], join(runPath, 'working-directory'), issues);
	if (out.workingDirectory) checkTemplates(out.workingDirectory, join(runPath, 'working-directory'), issues, at);
	return out;
}

function concurrencyValue(value: unknown, path: string, issues: Issues, at: Where): { group: string; cancelInProgress: boolean } | null {
	if (value === undefined || value === null) return null;
	let group: string | null;
	let cancelInProgress = false;
	if (isMap(value)) {
		checkKeys(value, ['group', 'cancel-in-progress'], path, issues);
		group = optionalString(value.group, join(path, 'group'), issues);
		if (group === null && value.group === undefined) issues.add(join(path, 'group'), 'concurrency.group is required');
		cancelInProgress = booleanValue(value['cancel-in-progress'], join(path, 'cancel-in-progress'), issues, false);
	} else {
		group = optionalString(value, path, issues);
	}
	if (group === null) return null;
	if (group.trim() === '') {
		issues.add(path, 'The concurrency group must not be empty');
		return null;
	}
	checkTemplates(group, isMap(value) ? join(path, 'group') : path, issues, at);
	return { group, cancelInProgress };
}

function timeoutValue(value: unknown, path: string, issues: Issues): number | null {
	if (value === undefined || value === null) return null;
	const n = typeof value === 'number' ? value : typeof value === 'string' && /^\s*\d+(\.\d+)?\s*$/.test(value) ? Number(value) : Number.NaN;
	if (Number.isNaN(n)) {
		issues.add(path, typeof value === 'string' && hasTemplate(value) ? 'Expressions are not supported in timeout-minutes yet; use a number' : `Expected a number of minutes, got ${describe(value)}`);
		return null;
	}
	if (n <= 0 || n > MAX_TIMEOUT_MINUTES) {
		issues.add(path, `timeout-minutes must be between 1 and ${MAX_TIMEOUT_MINUTES}`);
		return null;
	}
	return n;
}

function continueOnErrorValue(value: unknown, path: string, issues: Issues, at: Where): boolean | string {
	if (value === undefined || value === null) return false;
	if (typeof value === 'boolean') return value;
	if (value === 'true' || value === 'false') return value === 'true';
	if (typeof value === 'string' && hasTemplate(value)) {
		checkTemplates(value, path, issues, at);
		return value;
	}
	issues.add(path, `Expected true, false or an expression, got ${describe(value)}`);
	return false;
}

// --- container options --------------------------------------------------------------------

/** Split a docker-style options string on whitespace, honouring single and double quotes. */
function splitOptions(text: string): string[] {
	const out: string[] = [];
	let current = '';
	let quote: string | null = null;
	let started = false;
	for (const c of text) {
		if (quote) {
			if (c === quote) quote = null;
			else current += c;
		} else if (c === '"' || c === "'") {
			quote = c;
			started = true;
		} else if (/\s/.test(c)) {
			if (started) out.push(current);
			current = '';
			started = false;
		} else {
			current += c;
			started = true;
		}
	}
	if (started) out.push(current);
	return out;
}

/**
 * GitHub passes `options:` to `docker create`. Skiff starts containers through a fixed helper
 * verb (W5), so only `--health-cmd` (for service readiness) is understood; anything else would be
 * a flag the helper must not pass through.
 */
function healthCmdFromOptions(text: string, path: string, issues: Issues): string | null {
	const parts = splitOptions(text);
	let health: string | null = null;
	for (let i = 0; i < parts.length; i++) {
		const part = parts[i]!;
		if (part.startsWith('--health-cmd=')) {
			health = part.slice('--health-cmd='.length);
		} else if (part === '--health-cmd') {
			const next = parts[i + 1];
			if (next === undefined) issues.add(path, '--health-cmd needs a command');
			else health = next;
			i++;
		} else if (/^--health-(interval|timeout|retries|start-period)(=.+)?$/.test(part)) {
			// Accepted and ignored: Skiff polls the health command on its own schedule, and these
			// appear in nearly every `services:` block copied from GitHub.
			if (!part.includes('=')) i++;
		} else {
			issues.add(path, `Container option '${part}' is not supported (only --health-cmd and --health-* timings)`);
		}
	}
	return health;
}

function containerValue(value: unknown, path: string, issues: Issues, allowString: boolean): PipelineContainerSpec | null {
	if (value === undefined || value === null) return null;
	if (typeof value === 'string' && allowString) {
		if (value.trim() === '') {
			issues.add(path, 'The container image must not be empty');
			return null;
		}
		checkTemplates(value, path, issues, W.job);
		return { image: value, env: {}, ports: [], healthCmd: null };
	}
	if (!isMap(value)) {
		issues.add(path, `Expected ${allowString ? 'an image or ' : ''}a mapping, got ${describe(value)}`);
		return null;
	}
	checkKeys(value, ['image', 'env', 'ports', 'options'], path, issues);
	const image = optionalString(value.image, join(path, 'image'), issues);
	if (!image || image.trim() === '') issues.add(join(path, 'image'), 'image is required');
	else checkTemplates(image, join(path, 'image'), issues, W.job);
	const env = templateMap(value.env, join(path, 'env'), issues, W.containerEnv, true);
	const ports = stringList(value.ports, join(path, 'ports'), issues) ?? [];
	for (const [index, port] of ports.entries()) {
		if (!/^\d{1,5}(:\d{1,5})?(\/(tcp|udp))?$/.test(port)) issues.add(`${join(path, 'ports')}[${index}]`, `Invalid port '${port}' (use "5432" or "8080:80")`);
	}
	const options = optionalString(value.options, join(path, 'options'), issues);
	const healthCmd = options ? healthCmdFromOptions(options, join(path, 'options'), issues) : null;
	return { image: image ?? '', env, ports, healthCmd };
}

