/**
 * Workflow parsing, validation and planning helpers (docs/PIPELINES.md §5, W1).
 *
 * The caller YAML-parses `.skiff/workflows/*.yml` (Bun.YAML) and hands the plain value to
 * `parseWorkflow`, which accepts exactly the documented subset of GitHub Actions syntax. Unknown
 * keys are errors rather than silently ignored (W1): a workflow that half-runs because a key was
 * dropped is worse than one that refuses to start. Every problem is collected, with a path like
 * `jobs.build.steps[2].with.key`, so `skif workflow lint` and the dashboard can show them all at
 * once.
 *
 * Pure TypeScript (no Bun/Node APIs) so the dashboard can lint in the browser.
 */

export class PipelineWorkflowError extends Error {
	issues: PipelineWorkflowIssue[];

	constructor(issues: PipelineWorkflowIssue[]) {
		super(issues.map((issue) => (issue.path ? `${issue.path}: ${issue.message}` : issue.message)).join('\n'));
		this.name = 'PipelineWorkflowError';
		this.issues = issues;
	}
}

