const TOP_KEYS = ['name', 'run-name', 'on', 'env', 'defaults', 'concurrency', 'permissions', 'jobs'];
const JOB_KEYS = [
	'name',
	'needs',
	'if',
	'runs-on',
	'strategy',
	'outputs',
	'env',
	'defaults',
	'timeout-minutes',
	'continue-on-error',
	'concurrency',
	'environment',
	'container',
	'services',
	'steps',
	'permissions',
];
const JOB_HINTS: Record<string, string> = {
	with: 'with: belongs on a uses: step, or on a job that calls a reusable workflow (jobs.<id>.uses)',
	secrets: 'secrets: only applies to a job that calls a reusable workflow (jobs.<id>.uses)',
};
/** GitHub's list of keys a job calling a reusable workflow may have. */
const CALLER_JOB_KEYS = ['name', 'uses', 'with', 'secrets', 'needs', 'if', 'strategy', 'concurrency', 'permissions'];
/** Reusable workflows are read from the calling commit's own `.skiff/workflows`. */
const LOCAL_WORKFLOW = /^\.\/\.skiff\/workflows\/[A-Za-z0-9._-]+\.ya?ml$/;
const REMOTE_WORKFLOW = /^[A-Za-z0-9-]+\/[A-Za-z0-9._-]+\/\.(skiff|github)\/workflows\/[^@]+\.ya?ml@.+$/;
const STEP_KEYS = ['id', 'name', 'if', 'run', 'shell', 'working-directory', 'uses', 'with', 'env', 'continue-on-error', 'timeout-minutes'];

/**
 * `permissions:` is accepted and ignored for now: job tokens are already scoped to the job's
 * repository and trust tier (W9/W10), and mapping GitHub scopes onto them is later work. Accepting
 * it means workflows copied from GitHub keep parsing. The shape is still checked.
 */
function checkPermissions(value: unknown, path: string, issues: Issues): void {
	if (value === undefined || value === null || typeof value === 'string') return;
	if (!isMap(value)) {
		issues.add(path, `Expected read-all, write-all or a mapping, got ${describe(value)}`);
		return;
	}
	for (const [scope, level] of Object.entries(value)) {
		if (level !== 'read' && level !== 'write' && level !== 'none') issues.add(join(path, scope), 'Expected read, write or none');
	}
}

function runsOnValue(value: unknown, path: string, issues: Issues): string[] {
	if (value === undefined || value === null) {
		issues.add(path, 'runs-on is required (the labels a node must offer, e.g. [linux])');
		return [];
	}
	let labels: string[] | null;
	if (isMap(value)) {
		// Runner groups do not exist in Skiff; labels alone decide placement, so `group` is ignored.
		checkKeys(value, ['group', 'labels'], path, issues);
		labels = stringList(value.labels, join(path, 'labels'), issues);
	} else {
		labels = stringList(value, path, issues);
	}
	if (!labels || labels.length === 0) {
		issues.add(path, 'runs-on needs at least one label');
		return [];
	}
	labels.forEach((label, index) => checkTemplates(label, Array.isArray(value) ? `${path}[${index}]` : path, issues, W.job));
	return labels;
}

function strategyValue(value: unknown, path: string, issues: Issues): PipelineJobSpec['strategy'] {
	const out: PipelineJobSpec['strategy'] = { matrix: null, failFast: true, maxParallel: null };
	if (value === undefined || value === null) return out;
	if (!isMap(value)) {
		issues.add(path, `Expected a mapping, got ${describe(value)}`);
		return out;
	}
	checkKeys(value, ['matrix', 'fail-fast', 'max-parallel'], path, issues);
	out.failFast = booleanValue(value['fail-fast'], join(path, 'fail-fast'), issues, true);
	const maxParallel = value['max-parallel'];
	if (maxParallel !== undefined && maxParallel !== null) {
		if (typeof maxParallel === 'number' && Number.isInteger(maxParallel) && maxParallel > 0) out.maxParallel = maxParallel;
		else issues.add(join(path, 'max-parallel'), 'max-parallel must be a positive whole number');
	}
	const matrix = value.matrix;
	const matrixPath = join(path, 'matrix');
	if (matrix === undefined || matrix === null) return out;
	if (typeof matrix === 'string') {
		if (unwrapExpressionSafe(matrix) === null) issues.add(matrixPath, 'A matrix string must be a single ${{ }} expression, e.g. ${{ fromJSON(inputs.matrix) }}');
		checkTemplates(matrix, matrixPath, issues, W.strategy);
		out.matrix = matrix;
		return out;
	}
	if (!isMap(matrix)) {
		issues.add(matrixPath, `Expected a mapping of axes, got ${describe(matrix)}`);
		return out;
	}
	let dynamic = false;
	const issuesBefore = issues.list.length;
	for (const [key, axis] of Object.entries(matrix)) {
		const axisPath = join(matrixPath, key);
		if (typeof axis === 'string' && hasTemplate(axis)) {
			checkTemplates(axis, axisPath, issues, W.strategy);
			dynamic = true;
			continue;
		}
		if (!Array.isArray(axis)) {
			issues.add(axisPath, key === 'include' || key === 'exclude' ? `Expected a list of mappings, got ${describe(axis)}` : `A matrix axis must be a list of values, got ${describe(axis)}`);
			continue;
		}
		if ((key === 'include' || key === 'exclude') && axis.some((item) => !isMap(item))) {
			issues.add(axisPath, `Each ${key} entry must be a mapping`);
			continue;
		}
		if (checkTemplatesDeep(axis, axisPath, issues, W.strategy)) dynamic = true;
	}
	// Expand static matrices now so size and include/exclude mistakes surface at lint time.
	if (!dynamic && issues.list.length === issuesBefore) {
		try {
			if (expandMatrix(matrix).length === 0) issues.add(matrixPath, 'The matrix produces no jobs');
		} catch (error) {
			if (!(error instanceof PipelineWorkflowError)) throw error;
			for (const issue of error.issues) issues.add(issue.path ? join(path, issue.path) : matrixPath, issue.message);
		}
	}
	out.matrix = matrix;
	return out;
}

function unwrapExpressionSafe(value: string): string | null {
	try {
		return unwrapExpression(value);
	} catch {
		return null;
	}
}

function environmentValue(value: unknown, path: string, issues: Issues): PipelineJobSpec['environment'] {
	if (value === undefined || value === null) return null;
	if (typeof value === 'string') {
		if (value.trim() === '') {
			issues.add(path, 'The environment name must not be empty');
			return null;
		}
		checkTemplates(value, path, issues, W.job);
		return { name: value, url: null };
	}
	if (!isMap(value)) {
		issues.add(path, `Expected a name or { name, url }, got ${describe(value)}`);
		return null;
	}
	checkKeys(value, ['name', 'url'], path, issues);
	const name = optionalString(value.name, join(path, 'name'), issues);
	if (!name || name.trim() === '') {
		issues.add(join(path, 'name'), 'environment.name is required');
		return null;
	}
	checkTemplates(name, join(path, 'name'), issues, W.job);
	const url = optionalString(value.url, join(path, 'url'), issues);
	if (url) checkTemplates(url, join(path, 'url'), issues, W.environmentUrl);
	return { name, url };
}

interface StepRules {
	step: Where;
	stepIf: Where;
	/** Composite-action steps: `shell` is required on run steps and there is no `timeout-minutes`. */
	composite: boolean;
}

const WORKFLOW_STEP: StepRules = { step: W.step, stepIf: W.stepIf, composite: false };
const COMPOSITE_STEP: StepRules = { step: W.step, stepIf: W.stepIf, composite: true };

function stepValue(value: unknown, path: string, issues: Issues, seenIds: Set<string>, rules: StepRules = WORKFLOW_STEP): PipelineStepSpec | null {
	if (!isMap(value)) {
		issues.add(path, `Expected a step mapping, got ${describe(value)}`);
		return null;
	}
	checkKeys(value, rules.composite ? STEP_KEYS.filter((key) => key !== 'timeout-minutes') : STEP_KEYS, path, issues);
	if (rules.composite && value.run !== undefined && value.shell === undefined) issues.add(join(path, 'shell'), 'shell is required for run steps in a composite action');
	const id = optionalString(value.id, join(path, 'id'), issues);
	if (id !== null) {
		if (!IDENTIFIER.test(id)) issues.add(join(path, 'id'), 'Step ids start with a letter or _ and contain letters, digits, - and _');
		else if (seenIds.has(id.toLowerCase())) issues.add(join(path, 'id'), `Duplicate step id '${id}'`);
		seenIds.add(id.toLowerCase());
	}
	const run = value.run === undefined ? null : optionalString(value.run, join(path, 'run'), issues);
	const uses = value.uses === undefined ? null : optionalString(value.uses, join(path, 'uses'), issues);
	if ((value.run === undefined) === (value.uses === undefined)) issues.add(path, 'A step needs exactly one of run or uses');
	if (run !== null) {
		if (run.trim() === '') issues.add(join(path, 'run'), 'run must not be empty');
		checkTemplates(run, join(path, 'run'), issues, rules.step);
	}
	if (uses !== null) {
		const usesPath = join(path, 'uses');
		if (hasTemplate(uses)) issues.add(usesPath, 'uses cannot contain expressions');
		else {
			const ref = parsePipelineActionRef(uses);
			if (ref.kind === 'invalid') issues.add(usesPath, ref.message);
		}
	}
	if (value.with !== undefined && value.uses === undefined) issues.add(join(path, 'with'), 'with only applies to uses steps');
	for (const key of ['shell', 'working-directory']) {
		if (value[key] !== undefined && value.run === undefined) issues.add(join(path, key), `${key} only applies to run steps`);
	}
	const firstLine = (run ?? '').split('\n').find((line) => line.trim() !== '')?.trim() ?? '';
	const name = optionalString(value.name, join(path, 'name'), issues) ?? (uses !== null ? `Run ${uses}` : `Run ${firstLine}`);
	if (value.name !== undefined) checkTemplates(name, join(path, 'name'), issues, rules.step);
	const workingDirectory = optionalString(value['working-directory'], join(path, 'working-directory'), issues);
	if (workingDirectory) checkTemplates(workingDirectory, join(path, 'working-directory'), issues, rules.step);
	return {
		id,
		name,
		if: condition(value.if, join(path, 'if'), issues, rules.stepIf),
		run,
		shell: shellValue(value.shell, join(path, 'shell'), issues, rules.composite),
		workingDirectory,
		uses,
		with: templateMap(value.with, join(path, 'with'), issues, rules.step),
		env: templateMap(value.env, join(path, 'env'), issues, rules.step, true),
		continueOnError: continueOnErrorValue(value['continue-on-error'], join(path, 'continue-on-error'), issues, rules.step),
		timeoutMinutes: timeoutValue(value['timeout-minutes'], join(path, 'timeout-minutes'), issues),
	};
}

/** `jobs.<id>.uses`: the repository-relative path of a local reusable workflow, or null. */
function reusableWorkflowPath(uses: string, path: string, issues: Issues): string | null {
	const text = uses.trim();
	if (hasTemplate(text)) {
		issues.add(path, 'uses cannot contain expressions');
		return null;
	}
	if (REMOTE_WORKFLOW.test(text)) {
		issues.add(path, `Remote reusable workflows are not supported yet; copy it to ${PIPELINE_WORKFLOW_DIR}/ and call it as ./${PIPELINE_WORKFLOW_DIR}/<file>.yml`);
		return null;
	}
	if (text.startsWith('./') && text.includes('@')) {
		issues.add(path, 'A local reusable workflow takes no @ref: it is read from the same commit');
		return null;
	}
	if (!LOCAL_WORKFLOW.test(text)) {
		issues.add(path, `Expected a reusable workflow path like ./${PIPELINE_WORKFLOW_DIR}/build.yml`);
		return null;
	}
	return text.slice(2);
}

/**
 * A job that calls a reusable workflow (`uses: ./.skiff/workflows/x.yml`). Only GitHub's caller
 * keys are allowed; the result has no steps or labels, which the engine fills in by inlining the
 * called workflow's jobs.
 */
function callerJobValue(key: string, value: Record<string, unknown>, path: string, issues: Issues, ownPath: string): PipelineJobSpec {
	const forbidden = Object.keys(value).filter((name) => !CALLER_JOB_KEYS.includes(name));
	for (const name of forbidden) {
		const known = JOB_KEYS.includes(name);
		issues.add(
			join(path, name),
			known
				? `A job that calls a reusable workflow cannot have ${name}: (set it in the called workflow)`
				: `Unknown key '${name}' (allowed with uses: ${CALLER_JOB_KEYS.join(', ')})`,
		);
	}
	checkPermissions(value.permissions, join(path, 'permissions'), issues);
	const name = optionalString(value.name, join(path, 'name'), issues) ?? key;
	if (value.name !== undefined) checkTemplates(name, join(path, 'name'), issues, W.job);
	const usesPath = join(path, 'uses');
	const usesText = optionalString(value.uses, usesPath, issues);
	const workflowPath = usesText === null ? null : reusableWorkflowPath(usesText, usesPath, issues);
	if (workflowPath !== null && workflowPath === ownPath) issues.add(usesPath, 'A workflow cannot call itself');
	let secrets: PipelineJobSpec['secrets'] = null;
	const secretsPath = join(path, 'secrets');
	if (value.secrets === 'inherit') secrets = 'inherit';
	else if (typeof value.secrets === 'string') issues.add(secretsPath, "Expected 'inherit' or a mapping of secrets");
	else if (value.secrets !== undefined && value.secrets !== null) {
		secrets = templateMap(value.secrets, secretsPath, issues, W.callSecrets);
		for (const secretName of Object.keys(secrets)) {
			if (!SECRET_NAME.test(secretName)) issues.add(join(secretsPath, secretName), 'Secret names are letters, digits and underscores');
		}
	}
	return {
		key,
		name,
		needs: [...new Set(stringList(value.needs, join(path, 'needs'), issues) ?? [])],
		if: condition(value.if, join(path, 'if'), issues, W.jobIf),
		runsOn: [],
		strategy: strategyValue(value.strategy, join(path, 'strategy'), issues),
		outputs: {},
		env: {},
		defaults: { shell: null, workingDirectory: null },
		timeoutMinutes: DEFAULT_TIMEOUT_MINUTES,
		continueOnError: false,
		concurrency: concurrencyValue(value.concurrency, join(path, 'concurrency'), issues, W.job),
		environment: null,
		container: null,
		services: {},
		steps: [],
		uses: workflowPath === null ? (usesText ?? '') : `./${workflowPath}`,
		with: templateMap(value.with, join(path, 'with'), issues, W.callWith),
		secrets,
	};
}

function jobValue(key: string, value: unknown, path: string, issues: Issues, ownPath: string): PipelineJobSpec | null {
	if (!IDENTIFIER.test(key)) issues.add(path, 'Job ids start with a letter or _ and contain letters, digits, - and _');
	if (!isMap(value)) {
		issues.add(path, `Expected a job mapping, got ${describe(value)}`);
		return null;
	}
	if (value.uses !== undefined) return callerJobValue(key, value, path, issues, ownPath);
	checkKeys(value, JOB_KEYS, path, issues, JOB_HINTS);
	checkPermissions(value.permissions, join(path, 'permissions'), issues);
	const name = optionalString(value.name, join(path, 'name'), issues) ?? key;
	if (value.name !== undefined) checkTemplates(name, join(path, 'name'), issues, W.job);
	const needs = [...new Set(stringList(value.needs, join(path, 'needs'), issues) ?? [])];

	const services: Record<string, PipelineContainerSpec> = {};
	const servicesPath = join(path, 'services');
	if (value.services !== undefined && value.services !== null) {
		if (!isMap(value.services)) issues.add(servicesPath, `Expected a mapping of services, got ${describe(value.services)}`);
		else {
			for (const [serviceKey, spec] of Object.entries(value.services)) {
				const servicePath = join(servicesPath, serviceKey);
				if (!IDENTIFIER.test(serviceKey)) issues.add(servicePath, 'Service names start with a letter or _ and contain letters, digits, - and _');
				const service = containerValue(spec, servicePath, issues, false);
				if (service) services[serviceKey] = service;
			}
		}
	}

	const steps: PipelineStepSpec[] = [];
	const stepsPath = join(path, 'steps');
	if (!Array.isArray(value.steps) || value.steps.length === 0) {
		issues.add(stepsPath, 'A job needs at least one step');
	} else {
		const seenIds = new Set<string>();
		value.steps.forEach((raw, index) => {
			const step = stepValue(raw, `${stepsPath}[${index}]`, issues, seenIds);
			if (step) steps.push(step);
		});
	}

	return {
		key,
		name,
		needs,
		if: condition(value.if, join(path, 'if'), issues, W.jobIf),
		runsOn: runsOnValue(value['runs-on'], join(path, 'runs-on'), issues),
		strategy: strategyValue(value.strategy, join(path, 'strategy'), issues),
		outputs: templateMap(value.outputs, join(path, 'outputs'), issues, W.jobOutputs),
		env: templateMap(value.env, join(path, 'env'), issues, W.jobEnv, true),
		defaults: defaultsValue(value.defaults, join(path, 'defaults'), issues, W.jobDefaults),
		timeoutMinutes: timeoutValue(value['timeout-minutes'], join(path, 'timeout-minutes'), issues) ?? DEFAULT_TIMEOUT_MINUTES,
		continueOnError: continueOnErrorValue(value['continue-on-error'], join(path, 'continue-on-error'), issues, W.job),
		concurrency: concurrencyValue(value.concurrency, join(path, 'concurrency'), issues, W.job),
		environment: environmentValue(value.environment, join(path, 'environment'), issues),
		container: containerValue(value.container, join(path, 'container'), issues, true),
		services,
		steps,
	};
}

/** Report unknown `needs` and dependency cycles (each cycle once, named in order). */
function checkNeeds(jobs: Record<string, PipelineJobSpec>, issues: Issues): void {
	for (const job of Object.values(jobs)) {
		for (const need of job.needs) {
			if (need === job.key) issues.add(`jobs.${job.key}.needs`, `Job '${job.key}' cannot need itself`);
			else if (!Object.hasOwn(jobs, need)) issues.add(`jobs.${job.key}.needs`, `Job '${job.key}' needs unknown job '${need}'`);
		}
	}
	const state = new Map<string, 'visiting' | 'done'>();
	const stack: string[] = [];
	const visit = (key: string): void => {
		state.set(key, 'visiting');
		stack.push(key);
		for (const need of jobs[key]!.needs) {
			if (need === key || !Object.hasOwn(jobs, need)) continue;
			const seen = state.get(need);
			if (seen === 'visiting') {
				const cycle = [...stack.slice(stack.indexOf(need)), need];
				issues.add(`jobs.${key}.needs`, `Dependency cycle: ${cycle.join(' → ')}`);
			} else if (seen === undefined) {
				visit(need);
			}
		}
		stack.pop();
		state.set(key, 'done');
	};
	for (const key of Object.keys(jobs)) if (!state.has(key)) visit(key);
}

